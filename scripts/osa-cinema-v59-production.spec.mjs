import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

test('V59 owner-local production desk: create, review, export, clear, import and cross-tab sync',async ({page,context},info)=>{
  const errors=[]
  page.on('pageerror',err=>errors.push(err.message))
  const response=await page.goto('/osa-cinema/studio/production?lang=en')
  expect(response.status()).toBe(200)
  const desk=page.locator('main.osa-production-page')
  await expect(desk).toBeVisible()
  await expect(desk).toHaveAttribute('data-studio-release','no-go')
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content','noindex,follow')
  await expect(desk.getByRole('heading',{name:'PRODUCTION. WITH CLARITY.'})).toBeVisible()
  await expect(desk.getByText('Zero Window',{exact:false}).first()).toBeVisible()
  expect(await desk.locator('.osa-production-scene-grid button').count()).toBe(14)
  await desk.getByRole('button',{name:/S02/}).click()
  await desk.getByRole('textbox',{name:'Task title'}).fill('Audit location agreement')
  await desk.getByRole('textbox',{name:'Owner (optional)'}).fill('Producer')
  await desk.getByRole('textbox',{name:'Notes'}).fill('Prepare paperwork for review.')
  await desk.getByRole('button',{name:/Add to local plan/}).click()
  const card=desk.locator('.osa-production-task',{hasText:'Audit location agreement'})
  await expect(card).toBeVisible()
  await card.getByRole('combobox',{name:'Task status: Audit location agreement'}).selectOption('in_progress')
  await expect(card.locator('.osa-production-state')).toHaveText('In progress')
  const [json]=await Promise.all([page.waitForEvent('download'),desk.getByRole('button',{name:'Export JSON'}).click()])
  const backup=readFileSync(await json.path(),'utf8')
  const data=JSON.parse(backup)
  expect(data.schema).toBe('OSA_CINEMA_PRODUCTION_DRAFT_V1')
  expect(data.publicReleaseAuthorized).toBe(false)
  expect(data.dataIsNotFilmingEvidence).toBe(true)
  expect(data.tasks).toHaveLength(1)
  expect(data.tasks[0].status).toBe('in_progress')
  const [csv]=await Promise.all([page.waitForEvent('download'),desk.getByRole('button',{name:'Export CSV'}).click()])
  expect(csv.suggestedFilename()).toBe('OSA-CINEMA-production-draft-v1.csv')
  expect(readFileSync(await csv.path(),'utf8')).toContain('"S02"')
  await desk.getByRole('button',{name:'Clear plan'}).click()
  await desk.getByRole('button',{name:'Confirm clear'}).click()
  await expect(desk.locator('.osa-production-task')).toHaveCount(0)
  await desk.locator('#osa-production-import').setInputFiles({name:'restore.json',mimeType:'application/json',buffer:Buffer.from(backup)})
  await expect(desk.locator('.osa-production-task')).toHaveCount(1)
  await expect(desk.getByRole('status').filter({hasText:'Draft restored'})).toBeVisible()
  const second=await context.newPage()
  await second.goto('/osa-cinema/studio/production?lang=en')
  await second.getByRole('button',{name:/S02/}).click()
  await expect(second.locator('.osa-production-task')).toHaveCount(1)
  await card.getByRole('button',{name:'Delete task: Audit location agreement'}).click()
  await expect(second.locator('.osa-production-task')).toHaveCount(0)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
  expect(errors).toEqual([])
  await page.screenshot({path:info.outputPath('osa-cinema-v59-production-ui.png'),fullPage:true,animations:'disabled'})
})

test('V59 private planning accepts no forged film release and safely rejects imported data',async ({page},info)=>{
  await page.goto('/osa-cinema/studio/production?lang=ru')
  const desk=page.locator('main.osa-production-page')
  await expect(desk).toHaveAttribute('data-studio-release','no-go')
  await expect(desk.getByRole('heading',{name:'Никаких ложных премьер.'})).toBeVisible()
  await expect(desk.locator('video, source[src]')).toHaveCount(0)
  await expect(desk.locator('.osa-production-scoreboard strong').nth(2)).toContainText('0')
  const rogue={
    schema:'OSA_CINEMA_PRODUCTION_DRAFT_V1',version:1,project:'zero-window',
    storage:'local_device_only',dataIsNotFilmingEvidence:true,
    publicReleaseAuthorized:true,generatedAt:'2026-10-28T00:00:00.000Z',tasks:[]
  }
  await desk.locator('#osa-production-import').setInputFiles({name:'forged.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(rogue))})
  await expect(desk.getByRole('alert')).toContainText('Неверный формат')
  await expect(desk.locator('.osa-production-task')).toHaveCount(0)
  await desk.getByRole('button',{name:'Switch to English'}).click()
  await expect(page).toHaveURL(/lang=en/)
  await expect(desk.getByRole('heading',{name:'PRODUCTION. WITH CLARITY.'})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
  await page.setViewportSize({width:320,height:740})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
  await page.screenshot({path:info.outputPath('osa-cinema-v59-production-no-go.png'),fullPage:true,animations:'disabled'})
})

test('V59 producer desk is linked from the real Zero Window film, not an invented MP4 player',async ({page})=>{
  await page.goto('/osa-cinema/studio/films/zero-window?lang=en')
  const open=page.locator('.osa-film-actions a[href^="/osa-cinema/studio/production"]')
  await expect(open).toBeVisible()
  await open.click()
  await expect(page.locator('main.osa-production-page')).toBeVisible()
  await expect(page).toHaveURL(/\/osa-cinema\/studio\/production\?lang=en/)
  await expect(page.locator('.osa-studio-header a[href^="/osa-cinema/studio/films/zero-window"]')).toHaveAttribute('href','/osa-cinema/studio/films/zero-window?lang=en')
})
