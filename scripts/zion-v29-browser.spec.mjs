import {test,expect} from '@playwright/test'

async function city(page){
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/games/zion-9/queue/ZION-030/index.html?test=1')
 await page.waitForFunction(()=>window.__ZION030_OPEN_CITY__?.state().ready===true,null,{timeout:22000})
 await page.locator('#oc-entry').click()
 await page.locator('#oc-start-play').click()
 await expect(page.locator('#oc-shell')).toBeVisible()
 return errors
}

test('ZION v29: mission journal, two-step street operation and protected economy',async ({page})=>{
 test.setTimeout(90000)
 const errors=await city(page)
 const snapshot=()=>page.evaluate(()=>window.__ZION030_OPEN_CITY__.state())
 await page.locator('#oc-journal-button').click()
 await expect(page.locator('#oc-journal')).toBeVisible()
 await expect(page.locator('.oc-quest-row')).toHaveCount(5)
 await expect(page.locator('.oc-quest-row').first()).toHaveAttribute('aria-pressed','true')
 await page.locator('#oc-journal-resume').click()
 await page.evaluate(()=>window.__ZION030_OPEN_CITY__.teleport(-15,10))
 if(await page.locator('#oc-action').isVisible())await page.locator('#oc-action').click()
 else await page.keyboard.press('e')
 await expect.poll(async()=> (await snapshot()).dispatch.steps.school).toBe(1)
 await expect.poll(async()=> (await snapshot()).credits).toBe(0)
 await page.evaluate(()=>window.__ZION030_OPEN_CITY__.teleport(10,15))
 if(await page.locator('#oc-action').isVisible())await page.locator('#oc-action').click()
 else await page.keyboard.press('e')
 await expect.poll(async()=> (await snapshot()).dispatch.done.includes('school')).toBe(true)
 await expect.poll(async()=> (await snapshot()).credits).toBe(160)
 await page.locator('#oc-journal-button').click()
 await expect(page.locator('.oc-quest-row').first()).toContainText('160')
 await expect(page.locator('#oc-upgrade-grip')).toBeDisabled()
 await page.locator('#oc-journal-resume').click()
 await page.reload()
 await page.waitForFunction(()=>window.__ZION030_OPEN_CITY__?.state().ready===true,null,{timeout:22000})
 await page.locator('#oc-entry').click()
 await expect.poll(()=>page.evaluate(()=>window.__ZION030_OPEN_CITY__.state().credits)).toBe(160)
 await expect.poll(()=>page.evaluate(()=>window.__ZION030_OPEN_CITY__.state().dispatch.done.length)).toBe(1)
 expect(errors).toEqual([])
})

test('ZION v29: pause, camera switch, jump, district and minimap on desktop/mobile',async ({page},testInfo)=>{
 test.setTimeout(90000)
 const errors=await city(page)
 const snapshot=()=>page.evaluate(()=>window.__ZION030_OPEN_CITY__.state())
 await page.locator('#oc-view-button').evaluate(node=>node.click())
 await expect.poll(async()=> (await snapshot()).player.cameraMode).toBe('near')
 await page.locator('#oc-jump-button').evaluate(node=>node.click())
 await expect.poll(async()=> (await snapshot()).player.height).toBeGreaterThan(0)
 await page.locator('#oc-pause-button').click()
 await expect(page.locator('#oc-pause')).toBeVisible()
 await page.locator('#oc-pause-journal').click()
 await expect(page.locator('#oc-journal')).toBeVisible()
 await page.locator('#oc-journal-close').click()
 await expect(page.locator('#oc-journal')).toBeHidden()
 await page.evaluate(()=>window.__ZION030_OPEN_CITY__.teleport(0,-12))
 await expect.poll(async()=> (await snapshot()).district).toContain('')
 if(testInfo.project.name==='mobile'){
  await expect(page.locator('#oc-journal-button')).toBeVisible()
  await expect(page.locator('#oc-joystick')).toBeVisible()
 }
 await page.locator('#oc-exit').click()
 await expect(page.locator('#oc-shell')).toBeHidden()
 expect(errors).toEqual([])
})
