#!/usr/bin/env python3
"""Build the real NULL SHIFT Web export with the checksum-pinned official engine.

The toolchain cache contains only the Linux engine and single-thread release Web
template. Every cached member is verified before use; a cache hit is not trust.
Export metadata binds the generated bytes to this checkout's Godot source files.
"""
import argparse
import fcntl
import gzip
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / "godot/null-shift"
LOCK_PATH = ROOT / "godot/toolchain-lock.json"
LOCK = json.loads(LOCK_PATH.read_text())
REQUIRED = {"index.html", "index.js", "index.wasm", "index.pck"}
DEFAULT_OUTPUT = ROOT / "public/games/null-shift-godot"


def sha256(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def matches(path, record):
    return (not path.is_symlink() and path.is_file()
            and path.stat().st_size == record["bytes"]
            and sha256(path) == record["sha256"])


def download(archive, directory):
    path = directory / archive["cacheName"]
    if matches(path, archive):
        return path
    directory.mkdir(parents=True, exist_ok=True)
    # Download to a private file, validate, then publish. Never execute a partial
    # download or trust a GitHub cache entry solely because its name matches.
    for attempt in range(3):
        temporary = None
        try:
            print("Downloading official " + archive["cacheName"], flush=True)
            with tempfile.NamedTemporaryFile(dir=directory, delete=False) as target:
                temporary = Path(target.name)
                request = urllib.request.Request(archive["url"], headers={"User-Agent": "OSGARD-Godot-builder/1"})
                with urllib.request.urlopen(request, timeout=45) as response:
                    total = 0
                    while chunk := response.read(1024 * 1024):
                        total += len(chunk)
                        if total > archive["bytes"]:
                            raise ValueError("Official archive exceeds its locked size")
                        target.write(chunk)
            if not matches(temporary, archive):
                raise ValueError("Official archive checksum or size mismatch: " + archive["cacheName"])
            os.replace(temporary, path)
            return path
        except (OSError, ValueError):
            if temporary is not None:
                temporary.unlink(missing_ok=True)
            if attempt == 2:
                raise
            time.sleep(attempt + 1)


def install(cache, downloads):
    if sys.platform != "linux" or platform.machine().lower() not in ("x86_64", "amd64"):
        raise ValueError("The locked build toolchain requires Linux x86_64")
    cache.mkdir(parents=True, exist_ok=True)
    with (cache / ".install.lock").open("a") as lock_file:
        fcntl.flock(lock_file, fcntl.LOCK_EX)
        for archive in LOCK["archives"]:
            missing = [member for member in archive["members"] if not matches(cache / member["target"], member)]
            if not missing:
                continue
            archive_path = download(archive, downloads)
            with zipfile.ZipFile(archive_path) as zipped:
                for member in missing:
                    destination = cache / member["target"]
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    info = zipped.getinfo(member["name"])
                    if info.file_size != member["bytes"]:
                        raise ValueError("Unexpected archive member size: " + member["name"])
                    temporary = None
                    try:
                        with tempfile.NamedTemporaryFile(dir=destination.parent, delete=False) as target:
                            temporary = Path(target.name)
                            with zipped.open(info) as source:
                                shutil.copyfileobj(source, target, 1024 * 1024)
                        if not matches(temporary, member):
                            raise ValueError("Extracted toolchain checksum mismatch: " + member["name"])
                        temporary.chmod(0o755 if member.get("executable") else 0o644)
                        os.replace(temporary, destination)
                    finally:
                        if temporary is not None:
                            temporary.unlink(missing_ok=True)
    engine = cache / LOCK["archives"][0]["members"][0]["target"]
    engine.chmod(0o755)
    version = subprocess.check_output([str(engine), "--version"], text=True, timeout=20).strip()
    if version != LOCK["engineVersion"]:
        raise ValueError("Godot reports an unexpected version: " + version)
    return engine


def source_index():
    records = []
    for path in sorted(PROJECT.rglob("*")):
        relative = path.relative_to(PROJECT)
        if ".godot" in relative.parts:
            continue
        if path.is_symlink():
            raise ValueError("Godot build sources must not be symlinks: " + str(relative))
        if path.is_file():
            records.append({"path": relative.as_posix(), "bytes": path.stat().st_size, "sha256": sha256(path)})
    return records


def source_digest(records):
    return hashlib.sha256(json.dumps(records, ensure_ascii=False, separators=(",", ":")).encode()).hexdigest()


def export_records(directory):
    records = []
    for path in sorted(directory.iterdir()):
        if path.name == "build-info.json":
            continue
        if path.is_symlink() or not path.is_file():
            raise ValueError("Unexpected entry in Godot export: " + path.name)
        records.append({"path": path.name, "bytes": path.stat().st_size, "sha256": sha256(path)})
    if not REQUIRED <= {record["path"] for record in records}:
        raise ValueError("Godot export is missing required runtime files")
    return records


def verify_export(directory):
    if directory.is_symlink() or not directory.is_dir():
        raise ValueError("Expected a regular Godot export directory")
    metadata = directory / "build-info.json"
    if metadata.is_symlink() or not metadata.is_file() or metadata.stat().st_size > 1024 * 1024:
        raise ValueError("Expected bounded regular Godot export metadata")
    info = json.loads(metadata.read_text())
    if (not isinstance(info, dict) or type(info.get("schemaVersion")) is not int
            or info["schemaVersion"] != 1 or info.get("engineVersion") != LOCK["engineVersion"]):
        raise ValueError("Unsupported Godot export metadata or engine version")
    source = source_index()
    if (info.get("runtimeSmoke") != "passed" or type(info.get("sourceFiles")) is not int
            or info["sourceFiles"] != len(source)):
        raise ValueError("Godot export metadata does not record the complete successful build")
    if info.get("toolchainLockSha256") != sha256(LOCK_PATH):
        raise ValueError("Godot export was built with a different toolchain lock")
    if info.get("sourceSha256") != source_digest(source):
        raise ValueError("Godot export does not match the current source tree")
    if info.get("files") != export_records(directory):
        raise ValueError("Godot export bytes differ from its build metadata")
    wasm_path = directory / "index.wasm"
    packaging = info.get("packaging")
    if packaging is not None:
        if not isinstance(packaging, dict) or not isinstance(packaging.get("wasm"), dict):
            raise ValueError("Unsupported Godot transport encoding")
        wasm = packaging.get("wasm", {})
        if packaging.get("target") != "cloudflare-pages" or wasm.get("path") != "index.wasm" or wasm.get("contentEncoding") != "gzip":
            raise ValueError("Unsupported Godot transport encoding")
        with gzip.open(wasm_path, "rb") as stream:
            decoded = stream.read(64 * 1024 * 1024 + 1)
        if len(decoded) > 64 * 1024 * 1024 or len(decoded) != wasm.get("uncompressedBytes") or hashlib.sha256(decoded).hexdigest() != wasm.get("uncompressedSha256"):
            raise ValueError("Packaged Godot WASM differs from the original export")
        if decoded[:8] != b"\x00asm\x01\x00\x00\x00":
            raise ValueError("Decoded Godot asset is not WebAssembly")
    else:
        with wasm_path.open("rb") as stream:
            if stream.read(8) != b"\x00asm\x01\x00\x00\x00":
                raise ValueError("Godot export has an undeclared WebAssembly encoding")
    return info


def run_stage(name, command, env, logs, timeout):
    print("Godot stage: " + name, flush=True)
    result = subprocess.run(command, cwd=ROOT, env=env, text=True,
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=timeout)
    (logs / (name + ".log")).write_text(result.stdout)
    print(result.stdout, end="", flush=True)
    if result.returncode or re.search(r"SCRIPT ERROR:|Parse Error:|RUNTIME_SMOKE_FAILURE:|^ERROR:", result.stdout, re.MULTILINE):
        raise ValueError("Godot stage failed: " + name)
    if name == "runtime" and "PASS NULL//SHIFT runtime:" not in result.stdout:
        raise ValueError("Godot runtime smoke did not complete")


def build(cache, engine, output):
    # Exports are generated locally, never written into an arbitrary existing
    # directory. The standard ignored path may contain a previous manual export.
    if output.is_symlink():
        raise ValueError("Godot export destination must not be a symlink")
    if output.exists() and output != DEFAULT_OUTPUT and not (output / "build-info.json").is_file():
        raise ValueError("Refusing to replace an existing directory without Godot build metadata")
    logs = cache / "logs"
    logs.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ, XDG_DATA_HOME=str(cache / "data"), XDG_CONFIG_HOME=str(cache / "config"),
               XDG_CACHE_HOME=str(cache / "engine-cache"), GODOT_SILENCE_ROOT_WARNING="1")
    base = [str(engine), "--headless", "--path", str(PROJECT)]
    run_stage("import", [str(engine), "--headless", "--editor", "--path", str(PROJECT), "--quit"], env, logs, 120)
    before = source_index()
    # The smoke exercises real career persistence. Give each run a new user://
    # store so a previous purchase cannot alter the next build's starting state.
    # Import/export keep their verified template cache; existing saves stay intact.
    with tempfile.TemporaryDirectory(prefix="runtime-state-", dir=cache) as temporary_state:
        isolated = Path(temporary_state)
        runtime_env = dict(env, XDG_DATA_HOME=str(isolated / "data"),
                           XDG_CONFIG_HOME=str(isolated / "config"),
                           XDG_CACHE_HOME=str(isolated / "cache"))
        run_stage("runtime", base + ["--script", "res://tests/runtime_smoke.gd"], runtime_env, logs, 120)
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".null-shift-export-", dir=output.parent) as temporary:
        staged = Path(temporary)
        run_stage("export", base + ["--export-release", "Web", str(staged / "index.html")], env, logs, 180)
        if source_index() != before:
            raise ValueError("Godot sources changed while the export was being built; rebuild the candidate")
        subprocess.run(["node", "scripts/null-shift-godot-smoke.mjs", "--export-check", str(staged)], cwd=ROOT, check=True, timeout=30)
        info = {"schemaVersion": 1, "engineVersion": LOCK["engineVersion"],
                "toolchainLockSha256": sha256(LOCK_PATH), "sourceSha256": source_digest(before),
                "sourceFiles": len(before), "runtimeSmoke": "passed", "files": export_records(staged)}
        (staged / "build-info.json").write_text(json.dumps(info, ensure_ascii=False, indent=2) + "\n")
        verify_export(staged)
        if output.exists():
            allowed = {record["path"] for record in info["files"]} | {"build-info.json"}
            if any(path.name not in allowed or path.is_symlink() or not path.is_file() for path in output.iterdir()):
                raise ValueError("Refusing to replace unrecognized files in the Godot export destination")
            # This is an ignored local build directory, never a serving/deploy path.
            for path in output.iterdir():
                path.unlink()
            output.rmdir()
        os.replace(staged, output)
    return verify_export(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache-dir", type=Path, default=Path(os.environ.get("OSGARD_GODOT_CACHE", str(Path(tempfile.gettempdir()) / "osgard-godot-4.7.2"))))
    parser.add_argument("--download-dir", type=Path)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--install-only", action="store_true")
    parser.add_argument("--verify-export", type=Path)
    args = parser.parse_args()
    if args.verify_export:
        info = verify_export(args.verify_export.absolute())
        print(json.dumps({"status": "verified", "sourceSha256": info["sourceSha256"], "files": len(info["files"])}, indent=2))
        return
    cache = args.cache_dir.absolute()
    engine = install(cache, args.download_dir.absolute() if args.download_dir else cache / "downloads")
    if args.install_only:
        print(json.dumps({"status": "verified", "engine": str(engine), "xdgDataHome": str(cache / "data"), "version": LOCK["engineVersion"]}, indent=2))
        return
    info = build(cache, engine, args.output.absolute())
    print(json.dumps({"status": "built-and-verified", "output": str(args.output.absolute()), "sourceSha256": info["sourceSha256"], "files": len(info["files"])}, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.SubprocessError, zipfile.BadZipFile) as error:
        print("Godot build failed: " + str(error), file=sys.stderr)
        sys.exit(1)
