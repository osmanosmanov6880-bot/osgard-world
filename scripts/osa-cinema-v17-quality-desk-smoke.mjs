import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { Script } from 'node:vm'
const html=readFileSync('tools/osa-cinema-v17-quality-desk.html','utf8')
const report=JSON.parse(readFileSync('docs/OSA_CINEMA_V17_OBJECTIVE_QC_20261025.json','utf8'))
const video=JSON.parse(readFileSync('docs/OSA_CINEMA_V16_WORKPRINT_MANIFEST.json','utf8'))
const narration=JSON.parse(readFileSync('docs/OSA_CINEMA_V16_NARRATION_MANIFEST.json','utf8'))
const sourceMap=new Map([...video.assets,...narration.assets].map(asset=>[asset.file,asset]))
assert.equal(report.assets.length,10,'V17 must cover ten actual source files')
assert.equal(report.releaseAuthorization,false)
assert.ok(report.assets.every(a=>a.publicationApproved===false))
for(const a of report.assets){
  assert.equal(a.originalSha256,sourceMap.get(a.file)?.sha256)
  assert.equal(a.id,sourceMap.get(a.file)?.id,'Missing source UUID causes an empty editor file selector')
  assert.equal(a.locale,sourceMap.get(a.file)?.locale,'Missing language causes an empty editor file selector')
  assert.equal(a.expectedBytes,sourceMap.get(a.file)?.sizeBytes)
  assert.equal(a.audio?.scanExit,0,'Every audio track was actually decoded')
  assert.ok(Number.isFinite(a.audio?.integratedLufs))
  if(a.category==='video') assert.equal(a.video?.scanExit,0,'Each video was decoded')
}
assert.ok(html.includes('connect-src &#39;none&#39;') || html.includes("connect-src 'none'"),'CSP must disallow HTTP uploads')
assert.ok(html.includes("crypto.subtle.digest('SHA-256'"))
assert.ok(html.includes('releaseAuthorized:false') && html.includes('rightsVerified:false'))
assert.ok(html.includes('seenMarkers') && html.includes('currentTime'))
assert.ok(html.includes('URL.createObjectURL') && html.includes('URL.revokeObjectURL'))
assert.ok(html.includes('name="viewport"'))
assert.ok(html.includes('prefers-reduced-motion'))
assert.ok(!/<script\s+src=/i.test(html))
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)]
assert.equal(scripts.length,1)
assert.ok(!/\bfetch\s*\(|\bXMLHttpRequest\b|\bnavigator\.sendBeacon\b|\bWebSocket\b/.test(scripts[0][1]),'Private workprint must never upload to a remote host')
new Script(scripts[0][1],{filename:'osa-cinema-v17-quality-desk.html'})
const match=scripts[0][1].match(/const REPORT = (\{[^\n]*\});\nconst \$=/)
assert.ok(match,'Measured QC must be bundled in fully offline HTML')
const embedded=JSON.parse(match[1])
assert.equal(embedded.assets.length,10)
assert.deepEqual(embedded.assets.map(a=>a.id),report.assets.map(a=>a.id))
assert.ok(embedded.assets.every(a=>a.id && (a.locale==='ru'||a.locale==='en')))
assert.equal(embedded.releaseAuthorization,false)
console.log('OSA_CINEMA_V17_OFFLINE_DESK_PASS: all 10 original SHA anchors, live QC markers, offline player and fail-closed rights')
