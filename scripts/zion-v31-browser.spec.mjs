import { test, expect } from '@playwright/test'

// Real browser game-state acceptance. The geometry exists in the live Three.js scene,
// not merely in a render-only screenshot or mocked marketing page.
test('ZION-030 v31: cinematic PBR architecture, drivable detailing and weather-aware surfaces', async ({page},testInfo)=>{
  test.setTimeout(90000)
  const errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/games/zion-9/queue/ZION-030/index.html?test=1')
  await page.waitForFunction(()=>window.__ZION030_OPEN_CITY__?.state()?.ready,{},{timeout:30000})
  const state=()=>page.evaluate(()=>window.__ZION030_OPEN_CITY__.state())
  let scene=await state()
  expect(scene.cinematic).toBeTruthy()
  expect(scene.cinematic.version).toBe('31.0')
  expect(scene.cinematic.facades).toBeGreaterThan(40)
  expect(scene.cinematic.instances).toBeGreaterThan(200)
  expect(scene.cinematic.drawCallBatches).toBeLessThanOrEqual(44)
  expect(scene.cinematic.rooftopAssets).toBeGreaterThan(0)
  expect(scene.cinematic.foliageAssets).toBeGreaterThan(0)
  expect(scene.cinematic.vehicleParts).toBeGreaterThan(15)
  expect(scene.cinematic.avatarParts).toBeGreaterThan(5)
  expect(scene.cinematic.wetVisible).toBe(false)
  if(testInfo.project.name==='mobile')expect(['MOBILE','LITE']).toContain(scene.cinematic.tier)
  else expect(['ULTRA','LITE']).toContain(scene.cinematic.tier)
  expect(scene.mission.score).toBe(0)
  await page.locator('#oc-entry').click()
  await page.locator('#oc-start-play').click()
  await expect(page.locator('#oc-shell')).toBeVisible()
  await page.locator('#oc-rain').click()
  await expect.poll(async()=>(await state()).cinematic.wetVisible).toBe(true)
  await page.locator('#oc-time').click()
  await page.screenshot({path:testInfo.outputPath('zion-v31-cinematic-night-rain.png')})
  await page.locator('#oc-rain').click()
  await expect.poll(async()=>(await state()).cinematic.wetVisible).toBe(false)
  await page.locator('#oc-quality').click()
  await expect(page.locator('#oc-quality')).toContainText('ECO')
  expect((await state()).cinematic.highDetailVisible).toBe(false)
  await page.locator('#oc-quality').click()
  scene=await state()
  expect(scene.cinematic.highDetailVisible).toBe(scene.cinematic.tier==='ULTRA')
  await page.locator('#oc-exit').click()
  await expect(page.locator('#oc-shell')).toBeHidden()
  await expect(page.locator('#premiumPlace')).toBeAttached()
  expect(errors).toEqual([])
})
