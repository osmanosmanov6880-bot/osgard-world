import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('OSA Cinema V14 eight-scene guide is searchable, navigable and downloadable', async ({ page }, info) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/osa-cinema?lang=ru&utm_campaign=v14-qa')
  const guide = page.getByTestId('cinema-companion')
  await expect(guide).toBeVisible()
  await expect(guide.getByRole('heading', { name: 'Все восемь сцен. Один маршрут.' })).toBeVisible()
  const chapterNav = guide.getByRole('navigation', { name: 'Список сцен' })
  await expect(chapterNav.getByRole('button')).toHaveCount(8)
  await chapterNav.getByRole('button').nth(5).click()
  await expect(page).toHaveURL(/lang=ru/)
  await expect(page).toHaveURL(/scene=5/)
  await expect(page).toHaveURL(/utm_campaign=v14-qa/)
  await expect(chapterNav.getByRole('button').nth(5)).toHaveAttribute('aria-current', 'step')
  await expect(page.locator('.cinema-scene .scene-content h1')).toContainText('Не всякий контекст')

  await guide.getByRole('button', { name: 'Открыть полный сценарий' }).click()
  await expect(guide.locator('#cinema-companion-transcript')).toBeVisible()
  await expect(guide.locator('.cinema-companion__chapter')).toHaveCount(8)
  const search = guide.getByRole('searchbox', { name: 'Поиск по сценам' })
  await search.fill('Не всякий контекст')
  await expect(guide.locator('.cinema-companion__chapter')).toHaveCount(1)
  await expect(guide.locator('.cinema-companion__chapter h3')).toContainText('Не всякий контекст')
  await search.fill('слово-которого-нет-в-фильме')
  await expect(guide.locator('.cinema-companion__chapter')).toHaveCount(0)
  await expect(guide.getByText('Ничего не найдено. Попробуйте другое слово.')).toBeVisible()
  await search.clear()

  const event = page.waitForEvent('download')
  await guide.getByRole('button', { name: 'Сохранить текст' }).click()
  const download = await event
  expect(download.suggestedFilename()).toBe('osa-cinema-transcript-ru.txt')
  const localPath = await download.path()
  expect(localPath).toBeTruthy()
  const transcript = await readFile(localPath, 'utf8')
  expect(transcript).toContain('СЦЕНА 08 / 08')
  expect(transcript).toContain('СЦЕНА 01 / 08')
  expect(transcript).toContain('Не является записью фильма')
  expect(transcript).toContain('ВЫВОД:')
  await page.reload()
  await expect(page.locator('.cinema-scene .scene-content h1')).toContainText('Не всякий контекст')
  await expect(page).toHaveURL(/scene=5/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2)).toBe(true)
  expect(errors).toEqual([])
  await page.screenshot({ path: info.outputPath('osa-v14-ru-guide.png'), fullPage: true, animations: 'disabled' })
})

test('OSA Cinema V14 English deep links, manual sharing and honest narration status', async ({ page }, info) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/osa-cinema?lang=en&scene=2&source=shared')
  const guide = page.getByTestId('cinema-companion')
  await expect(guide).toBeVisible()
  await expect(page.locator('main.osa-cinema')).toHaveAttribute('lang', 'en')
  await expect(page.locator('.cinema-scene .scene-content h1')).toContainText('world’s library')
  const nav = guide.getByRole('navigation', { name: 'Scene index' })
  await expect(nav.getByRole('button').nth(2)).toHaveAttribute('aria-current', 'step')
  await expect(guide.getByText('Recorded movie audio and video have not yet been released.', { exact: false })).toBeVisible()

  await nav.getByRole('button').nth(7).click()
  await expect(page).toHaveURL(/scene=7/)
  await expect(page).toHaveURL(/source=shared/)
  await guide.getByRole('button', { name: 'Share scene link' }).click()
  await expect(guide.locator('.cinema-companion__feedback'))
    .toHaveText(/Scene link copied|Automatic copying is unavailable/)
  const manual = guide.locator('.cinema-companion__manual')
  if (await manual.count()) {
    await expect(manual).toHaveValue(/lang=en/)
    await expect(manual).toHaveValue(/scene=7/)
  }
  await guide.getByRole('button', { name: 'Open full transcript' }).click()
  await expect(guide.locator('.cinema-companion__chapter')).toHaveCount(8)
  await guide.getByRole('searchbox', { name: 'Search the scenes' }).fill('Generating an answer')
  await expect(guide.locator('.cinema-companion__chapter')).toHaveCount(1)

  await page.reload()
  await expect(page.locator('main.osa-cinema')).toHaveAttribute('lang', 'en')
  await expect(nav.getByRole('button').nth(7)).toHaveAttribute('aria-current', 'step')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2)).toBe(true)
  expect(errors).toEqual([])
  await page.screenshot({ path: info.outputPath('osa-v14-en-guide.png'), fullPage: true, animations: 'disabled' })
})
