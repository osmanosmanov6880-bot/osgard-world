import { expect, test } from '@playwright/test'

const dialog = page => page.getByRole('dialog', { name: 'Куда перейти?' })
const input = page => dialog(page).getByRole('combobox', { name: 'Поиск по разделам OSGARD' })

test('OSGARD discovery filters all genuine worlds, loads cover art and opens game details', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.keyboard.press('Control+k')
  await expect(dialog(page)).toBeVisible()
  const chips = dialog(page).getByRole('group', { name: 'Фильтр по направлениям' })
  await expect(chips.getByRole('button')).toHaveCount(5)
  await chips.getByRole('button', { name: 'Игры' }).click()
  await expect(chips.getByRole('button', { name: 'Игры' })).toHaveAttribute('aria-pressed', 'true')
  await expect(dialog(page).getByRole('option')).toHaveCount(23)
  await input(page).fill('добавь тень')
  const result = dialog(page).getByRole('option')
  await expect(result).toHaveCount(1)
  await expect(result).toHaveAttribute('data-command-id', 'game-zion-030')
  await expect(result).toHaveAttribute('href', '/play/world/zion-030')
  await expect(result.locator('img')).toHaveAttribute('src', '/brand/play/zion-030-640.webp')
  await expect.poll(() => result.locator('img').evaluate(img => img.naturalWidth)).toBeGreaterThan(0)
  await result.click()
  await expect(page).toHaveURL(/\/play\/world\/zion-030\/?$/)
  await expect(dialog(page)).toHaveCount(0)
  expect(errors).toEqual([])
})

test('Discovery recovers keyboard layout and reaches an actual OSA lesson', async ({ page }) => {
  await page.goto('/intelligence')
  await page.keyboard.press('Control+k')
  const finder = input(page)
  await finder.fill('frfltvbz')
  await expect(dialog(page).getByRole('option')).toHaveCount(1)
  await expect(dialog(page).getByRole('option')).toHaveAttribute('href', '/academy')
  await finder.fill('проверьте ответ ии')
  const option = dialog(page).getByRole('option')
  await expect(option).toHaveCount(1)
  await expect(option).toHaveAttribute('href', '/lectures/verify-an-ai-answer')
  await finder.press('Enter')
  await expect(page).toHaveURL(/\/lectures\/verify-an-ai-answer\/?$/)
  await expect(dialog(page)).toHaveCount(0)
})

test('Keyboard Home/End and contextual shortcuts stay usable inside the viewport', async ({ page }) => {
  await page.goto('/development')
  await page.keyboard.press('Control+k')
  const quick = dialog(page)
  const context = quick.getByRole('navigation', { name: 'Быстрые действия текущего раздела' })
  await expect(context.getByRole('link')).toHaveCount(3)
  await expect(context.getByRole('link').nth(0)).toHaveAttribute('href', '/development')
  const finder = input(page)
  await expect(quick.getByRole('option')).toHaveCount(43)
  await finder.press('End')
  await expect(quick.getByRole('option').last()).toHaveAttribute('aria-selected', 'true')
  await expect(quick.getByRole('option').last()).toBeInViewport()
  await finder.press('Home')
  await expect(quick.getByRole('option').first()).toHaveAttribute('aria-selected', 'true')
  await expect(quick.getByRole('option').first()).toBeInViewport()
  await page.keyboard.press('Escape')
  await expect(quick).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Быстрый переход по разделам OSGARD' })).toBeFocused()
})

