import {test,expect} from '@playwright/test'

test('V43 mobile navigator follows the real eight-scene RU/EN story',async ({page})=>{
 const errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.setViewportSize({width:390,height:844})
 await page.goto('/osa-cinema?lang=ru&scene=0')
 const cinema=page.locator('main.osa-cinema[data-cinema-art="obsidian"]')
 await expect(cinema).toBeVisible()
 const nav=cinema.getByRole('navigation',{name:'Быстрый переход между сценами'})
 await expect(nav).toBeVisible()
 const select=nav.getByRole('combobox',{name:'Выбрать сцену истории'})
 await expect(select.locator('option')).toHaveCount(8)
 await expect(select).toHaveValue('0')
 await expect(nav.getByRole('button',{name:'Предыдущая глава'})).toBeDisabled()
 await select.selectOption('4')
 await expect(select).toHaveValue('4')
 await expect(page).toHaveURL(/scene=4/)
 await expect(cinema.locator('.osa42-scene-heading')).toBeVisible()
 await nav.getByRole('button',{name:'Следующая глава'}).click()
 await expect(select).toHaveValue('5')
 await expect(page).toHaveURL(/scene=5/)
 await page.reload()
 await expect(select).toHaveValue('5')
 await cinema.getByRole('button',{name:'Switch to English'}).click()
 await expect(cinema).toHaveAttribute('lang','en')
 const english=cinema.getByRole('navigation',{name:'Quick scene navigation'})
 await expect(english.getByRole('combobox',{name:'Choose a story scene'})).toHaveValue('5')
 await expect(english.getByRole('button',{name:'Next chapter'})).toBeEnabled()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
 expect(errors).toEqual([])
})
test('desktop retains approved V42 archive with no mobile control clutter',async ({page})=>{
 await page.setViewportSize({width:1536,height:960})
 await page.goto('/osa-cinema?lang=en&scene=2')
 const cinema=page.locator('main.osa-cinema[data-cinema-art="obsidian"]')
 await expect(cinema).toBeVisible()
 await expect(cinema.locator('.osa43-mobile-nav')).toBeHidden()
 await expect(cinema.locator('.osa42-chapter')).toHaveCount(8)
 await expect(cinema.locator('.osa42-chapter[aria-current="step"]')).toHaveCount(1)
 await expect(cinema.locator('.osa42-scene-heading')).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
})
