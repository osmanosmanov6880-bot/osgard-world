import {test,expect} from '@playwright/test'

// Inspect actual rendered street assets and mission-preserving live WebGL state.
test('ZION-030 v33: street facades, sign atlas and animated EV survive cinematic weather and exit',async({page},testInfo)=>{
  test.setTimeout(90000)
  const errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/games/zion-9/queue/ZION-030/index.html?test=1')
  await page.waitForFunction(()=>window.__ZION030_OPEN_CITY__?.state()?.ready,null,{timeout:30000})
  const state=()=>page.evaluate(()=>window.__ZION030_OPEN_CITY__.state())
  const first=await state()
  expect(first.street).toBeTruthy()
  expect(first.street.version).toBe('33.0')
  expect(first.street.decoratedBuildings).toBeGreaterThanOrEqual(60)
  expect(first.street.arches).toBe(first.street.decoratedBuildings)
  expect(first.street.windowFrames).toBeGreaterThan(100)
  expect(first.street.instanceCount).toBeGreaterThan(400)
  expect(first.street.drawBatches).toBeLessThan(55)
  expect(first.street.shopSigns).toBe(first.street.tier==='LITE'?0:8)
  expect(first.street.vehicleCount).toBeGreaterThanOrEqual(3)
  expect(first.street.vehicleShells).toBe(first.street.vehicleCount)
  expect(first.street.animatedRims).toBe(first.street.vehicleCount*4)
  expect(first.street.characterParts).toBeGreaterThanOrEqual(5)
  expect(first.mission.score).toBe(0)
  if(testInfo.project.name==='mobile')expect(['LITE','MOBILE']).toContain(first.street.tier)
  else expect(['LITE','ULTRA']).toContain(first.street.tier)
  await page.locator('#oc-entry').click()
  await page.locator('#oc-start-play').click()
  await expect(page.locator('#oc-shell')).toBeVisible()
  await page.locator('#oc-rain').click()
  await expect.poll(async()=>(await state()).street.raining).toBe(true)
  await page.locator('#oc-time').click()
  expect((await state()).street.signLights).toBe(true)
  await page.screenshot({path:testInfo.outputPath('zion-v33-street-architecture-night-rain.png')})
  await page.locator('#oc-quality').click()
  await expect(page.locator('#oc-quality')).toContainText('ECO')
  expect((await state()).street.fineVisible).toBe(false)
  await page.locator('#oc-quality').click()
  expect((await state()).street.fineVisible).toBe(first.street.tier==='ULTRA')
  await page.locator('#oc-exit').click()
  await expect(page.locator('#oc-shell')).toBeHidden()
  await expect(page.locator('#premiumPlace')).toBeAttached()
  expect(errors).toEqual([])
})
