import {test,expect} from '@playwright/test'

// Evidence from the actual running browser/game engine. No mock scene is used.
test('ZION-030 v32: iconic rooftop assets and sculpted vehicles survive rain, night, ECO and game exit',async({page},testInfo)=>{
  test.setTimeout(90000)
  const errors=[]
  page.on('pageerror',err=>errors.push(err.message))
  await page.goto('/games/zion-9/queue/ZION-030/index.html?test=1')
  await page.waitForFunction(()=>window.__ZION030_OPEN_CITY__?.state()?.ready,null,{timeout:30000})
  const state=()=>page.evaluate(()=>window.__ZION030_OPEN_CITY__.state())
  const start=await state()
  expect(start.landmarks).toBeTruthy()
  expect(start.landmarks.version).toBe('32.0')
  expect(start.landmarks.rooftopBuildings).toBeGreaterThan(40)
  expect(start.landmarks.heroLandmarks).toBe(6)
  expect(start.landmarks.instances).toBeGreaterThan(300)
  expect(start.landmarks.instances).toBeLessThan(12000)
  expect(start.landmarks.drawCallBatches).toBeLessThanOrEqual(60)
  expect(start.landmarks.columns).toBeGreaterThan(0)
  expect(start.landmarks.roofFixtures).toBeGreaterThan(0)
  expect(start.landmarks.vehicleParts).toBeGreaterThan(50)
  expect(start.landmarks.vehicleCount).toBeGreaterThanOrEqual(3)
  expect(start.landmarks.maxVehicleBatches).toBeLessThanOrEqual(18)
  expect(start.landmarks.vehicleBatches).toBeLessThanOrEqual(start.landmarks.vehicleCount*18)
  expect(start.landmarks.characterParts).toBeGreaterThanOrEqual(5)
  if(testInfo.project.name==='mobile')expect(['MOBILE','LITE']).toContain(start.landmarks.tier)
  else expect(['ULTRA','LITE']).toContain(start.landmarks.tier)
  await page.locator('#oc-entry').click()
  await page.locator('#oc-start-play').click()
  await expect(page.locator('#oc-shell')).toBeVisible()
  await expect(page.locator('#oc-minimap')).toBeVisible()
  await page.locator('#oc-rain').click()
  await expect.poll(async()=>(await state()).landmarks.wetVisible).toBe(start.landmarks.tier!=='LITE')
  await page.locator('#oc-time').click()
  expect((await state()).landmarks.night).toBe(true)
  await page.screenshot({path:testInfo.outputPath('zion-v32-landmarks-night-rain.png')})
  await page.locator('#oc-quality').click()
  await expect(page.locator('#oc-quality')).toContainText('ECO')
  expect((await state()).landmarks.fineVisible).toBe(false)
  await page.locator('#oc-quality').click()
  expect((await state()).landmarks.fineVisible).toBe(start.landmarks.tier==='ULTRA')
  await page.locator('#oc-exit').click()
  await expect(page.locator('#oc-shell')).toBeHidden()
  await expect(page.locator('#premiumPlace')).toBeAttached()
  expect(errors).toEqual([])
})
