import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { build } from 'esbuild'
import { makePressKit,renderPressText,PRESS_KIT_SCHEMA } from './osa-cinema-v60-press-kit.mjs'
async function typedModule(path){
  const b=await build({entryPoints:[path],bundle:true,write:false,format:'esm',platform:'node'})
  return import('data:text/javascript;base64,'+Buffer.from(b.outputFiles[0].text).toString('base64'))
}
const [data,registry]=await Promise.all([typedModule('src/osaCinemaDistribution.ts'),typedModule('src/osaCinemaStudioRegistry.ts')])
const evidence=JSON.parse(readFileSync('docs/OSA_CINEMA_V53_CONCEPT_EVIDENCE_20261028.json','utf8'))
const press=makePressKit(registry.studioWorks,evidence,[data.publicReleaseDecision('zero-window'),data.publicReleaseDecision('threshold')])
const at='2026-10-29T00:00:00.000Z'
const seed={projectId:'zero-window',items:[]}
const note=data.updateReleaseNote(seed,'zw-rights','preparing','Need independently checked licence',at)

test('V60 immutable evidence never turns 0 filmed scenes into a public movie',()=>{
 assert.equal(evidence.actorSceneProduction.scenesFilmed,0)
 assert.equal(evidence.publicReleaseAuthorized,false)
 assert.equal(evidence.qa.publicHttps,'NOT_VERIFIED')
 assert.equal(data.releaseGates.length,13)
 const zw=data.publicReleaseDecision('zero-window')
 const th=data.publicReleaseDecision('threshold')
 assert.equal(zw.gates.length,8)
 assert.equal(th.gates.length,5)
 assert.equal(zw.releaseAuthorized,false)
 assert.equal(th.releaseAuthorized,false)
 assert.equal(zw.readyForRelease,false)
 assert.equal(th.readyForRelease,false)
 assert.equal(zw.publicVideoUrl,null)
 assert.equal(th.publicVideoUrl,null)
 assert.ok(zw.blocked>0&&th.blocked>0)
 assert.equal(zw.verified+zw.pending+zw.blocked,8)
 assert.equal(th.verified+th.pending+th.blocked,5)
})
test('Private distribution review is a project-isolated, bounded local planning note',()=>{
 assert.deepEqual(data.validateReleaseNotes(seed),seed)
 assert.deepEqual(data.validateReleaseNotes(note),note)
 assert.equal(note.items[0].status,'preparing')
 assert.deepEqual(data.validateReleaseNotes({projectId:'threshold',items:[...note.items]}),null)
 assert.equal(data.updateReleaseNote(seed,'th-rights','preparing','wrong project',at),null)
 assert.equal(data.updateReleaseNote(seed,'zw-rights','verified','fake approval',at),null)
 assert.equal(data.updateReleaseNote(seed,'zw-rights','ready_for_release','fake release',at),null)
 assert.equal(data.updateReleaseNote(seed,'zw-rights','preparing','x'.repeat(501),at),null)
 const changed=data.updateReleaseNote(note,'zw-rights','review_requested','only a local request',at)
 assert.equal(changed.items.length,1)
 assert.equal(changed.items[0].status,'review_requested')
 assert.equal(data.publicReleaseDecision('zero-window').releaseAuthorized,false)
 assert.equal(data.validateReleaseNotes({projectId:'zero-window',items:[note.items[0],note.items[0]]}),null)
 assert.equal(data.validateReleaseNotes({projectId:'zero-window',items:[{...note.items[0],note:'\u0001bad'}]}),null)
 assert.equal(data.validateReleaseNotes({projectId:'zero-window',items:[{...note.items[0],updatedAt:'tomorrow'}]}),null)
 assert.equal(data.validateReleaseNotes({projectId:'not-a-film',items:[]}),null)
})
test('Versioned local JSON export/import round-trip fails closed on fabricated authorization',()=>{
 const text=data.exportReleaseNotes(note,at)
 const parsed=JSON.parse(text)
 assert.equal(parsed.schema,'OSA_CINEMA_DISTRIBUTION_NOTES_V1')
 assert.equal(parsed.storage,'local_device_only')
 assert.equal(parsed.ownerPlanningOnly,true)
 assert.equal(parsed.releaseAuthorized,false)
 assert.equal(parsed.publicVideoUrl,null)
 assert.deepEqual(data.importReleaseNotes(text),note)
 const mutate=(patch)=>JSON.stringify({...parsed,...patch})
 for(const invalid of ['', '{', 'bad', 'a'.repeat(33000),
   mutate({schema:'UNKNOWN'}),mutate({version:3}),mutate({releaseAuthorized:true}),
   mutate({publicVideoUrl:'https://osgard.world/movie.mp4'}),mutate({ownerPlanningOnly:false}),
   mutate({projectId:'different'}),mutate({storage:'cloud'}),mutate({items:[{...note.items[0],status:'verified'}]}),
   mutate({items:[note.items[0],note.items[0]]})])assert.equal(data.importReleaseNotes(invalid),null)
 assert.deepEqual(data.readReleaseNotes('zero-window'),seed)
 assert.equal(data.saveReleaseNotes(note),false)
 assert.throws(()=>data.exportReleaseNotes({projectId:'zero-window',items:[{...note.items[0],status:'published'}]},at))
})
test('Public press JSON uses canonical typed registry and original V53 boundaries',()=>{
 assert.equal(press.schema,PRESS_KIT_SCHEMA)
 assert.equal(press.version,1)
 assert.equal(press.asOfEvidenceDate,'2026-10-28')
 assert.deepEqual(press.languages,['ru','en'])
 assert.equal(press.publicPremiereAuthorized,false)
 assert.equal(press.rightsIndependentlyVerified,false)
 assert.equal(press.allMoviePlaybackVerified,false)
 assert.equal(press.factualProduction.liveActionScenesPlanned,13)
 assert.equal(press.factualProduction.liveActionScenesFilmed,0)
 assert.equal(press.factualProduction.proposedShots,78)
 assert.equal(press.factualProduction.actualShotsFilmed,0)
 assert.equal(press.localConcept.durationSeconds,160)
 assert.equal(press.localConcept.subtitleTrackCount,2)
 assert.equal(press.projects.length,3)
 assert.deepEqual(press.projects.map(p=>p.id),['the-next-human','zero-window','threshold'])
 assert.deepEqual(press.projects.map(p=>p.releaseState),['interactive_public','not_filmed','owner_local'])
 assert.ok(press.projects.every(p=>p.titles.ru&&p.titles.en&&p.publicVideoAvailable===false&&p.publicMoviePremiere===false&&p.playbackUrl===null))
 assert.equal(press.projects.filter(p=>p.interactiveUrl!==null).length,1)
 assert.equal(press.projects[0].interactiveUrl,'https://osgard.world/osa-cinema')
 const serialized=JSON.stringify(press)
 assert.doesNotMatch(serialized,/signed_url|access_token|personal_data|checkout|\.mp4|\.m3u8|VideoObject|watchlist/i)
})
test('Public press generator rejects mismatched evidence, duplicates and fake film releases',()=>{
 const make=(works=registry.studioWorks,src=evidence,decisions=[data.publicReleaseDecision('zero-window'),data.publicReleaseDecision('threshold')])=>makePressKit(works,src,decisions)
 assert.throws(()=>make([],evidence))
 assert.throws(()=>make([...registry.studioWorks,registry.studioWorks[0]]))
 assert.throws(()=>make(registry.studioWorks.map((w,i)=>i===1?{...w,releaseState:'released'}:w)))
 assert.throws(()=>make(registry.studioWorks,{...evidence,publicReleaseAuthorized:true}))
 assert.throws(()=>make(registry.studioWorks,{...evidence,qa:{...evidence.qa,publicHttps:'PASS'}}))
 assert.throws(()=>make(registry.studioWorks,evidence,[{...data.publicReleaseDecision('zero-window'),releaseAuthorized:true},data.publicReleaseDecision('threshold')]))
})
test('Press sheets are bilingual factual summaries, not invented premieres',()=>{
 const ru=renderPressText(press,'ru'),en=renderPressText(press,'en')
 assert.ok(ru.includes('ПУБЛИЧНЫЙ СТАТУС: ФИЛЬМЫ НЕ ВЫПУЩЕНЫ'))
 assert.ok(en.includes('PUBLIC RELEASE: NO FILM PREMIERE'))
 assert.ok(ru.includes('НУЛЕВОЕ ОКНО'))
 assert.ok(en.includes('ZERO WINDOW'))
 assert.ok(ru.includes('https://osgard.world/osa-cinema/studio/films/zero-window'))
 assert.ok(en.includes('https://osgard.world/osa-cinema/studio/films/threshold'))
 assert.throws(()=>renderPressText(press,'fr'))
})
