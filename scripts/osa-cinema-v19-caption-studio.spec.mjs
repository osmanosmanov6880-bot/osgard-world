import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'
import {resolve} from 'node:path'
import {pathToFileURL} from 'node:url'

test('V19 local-only RU/EN caption editor handles actual 239s source clock, verified metadata and safe WebVTT export',async({page},info)=>{
 const errors=[],remote=[]
 page.on('pageerror',e=>errors.push(e.message))
 page.on('request',request=>{if(/^https?:/.test(request.url()))remote.push(request.url())})
 await page.goto(pathToFileURL(resolve('tools/osa-cinema-v19-caption-studio.html')).href)
 await expect(page.locator('#title')).toHaveText('Студия ручной синхронизации субтитров')
 await expect(page.locator('#source option')).toHaveCount(4)
 await page.locator('#source').selectOption('osa-v15-directors-ru')
 await expect(page.locator('#actMarkers button')).toHaveCount(3)
 await expect(page.locator('#cutMarkers button')).toHaveCount(64)
 await page.locator('#mp4').setInputFiles({name:'OSA_CINEMA_V15_DIRECTORS_WORKPRINT_RU_1080P.mp4',mimeType:'video/mp4',buffer:Buffer.from('INVALID MP4 BYTES: this is only a browser contract test')})
 await expect(page.locator('#status')).toContainText('не совпадают')
 await page.locator('#hash').click()
 await expect(page.locator('#status')).toContainText('не совпадают')
 const vtt='WEBVTT\n\n00:00:05.000 --> 00:00:07.000\nТестовая реплика для проверки\n\n00:01:19.000 --> 00:01:21.000\nВторой тестовый текст\n'
 await page.locator('#vtt').setInputFiles({name:'private-ru-draft.vtt',mimeType:'text/vtt',buffer:Buffer.from(vtt,'utf8')})
 await expect(page.locator('.cue-row')).toHaveCount(2)
 await page.locator('.cue-row').nth(1).click()
 await expect(page.locator('#start')).toHaveValue('00:01:19.000')
 await page.locator('#cueText').fill('Обновлённая проверочная реплика')
 await page.locator('#updateCue').click()
 await expect(page.locator('.cue-row').nth(1)).toContainText('Обновлённая проверочная реплика')
 await expect(page.locator('#status')).toContainText('текущий сеанс')
 await page.locator('#start').fill('00:01:20.000')
 await page.locator('#end').fill('00:01:23.000')
 await page.locator('#cueText').fill('Недопустимое пересечение')
 await page.locator('#addCue').click()
 await expect(page.locator('#status')).toContainText('overlap')
 await expect(page.locator('.cue-row')).toHaveCount(2)
 const vttDownloadPromise=page.waitForEvent('download')
 await page.locator('#exportVtt').click()
 const exported=await vttDownloadPromise
 expect(exported.suggestedFilename()).toContain('PRIVATE_ru_')
 const actualVtt=await readFile(await exported.path(),'utf8')
 expect(actualVtt).toContain('WEBVTT')
 expect(actualVtt).toContain('00:01:19.000 --> 00:01:21.000')
 expect(actualVtt).toContain('Обновлённая проверочная реплика')
 expect(actualVtt).not.toContain('Недопустимое пересечение')
 const reviewDownloadPromise=page.waitForEvent('download')
 await page.locator('#exportJson').click()
 const review=JSON.parse(await readFile(await (await reviewDownloadPromise).path(),'utf8'))
 expect(review.sourceId).toBe('osa-v15-directors-ru')
 expect(review.locale).toBe('ru')
 expect(review.releaseAuthorized).toBe(false)
 expect(review.rightsCleared).toBe(false)
 expect(review.captionsEditoriallyApproved).toBe(false)
 expect(review.sourceBytesVerified).toBe(false)
 expect(review.cues).toHaveLength(2)
 await page.locator('#source').selectOption('osa-v15-directors-en')
 await expect(page.locator('.cue-row')).toHaveCount(0)
 await page.locator('#switchLanguage').click()
 await expect(page.locator('#title')).toHaveText('Manual film caption studio')
 await expect(page.locator('#editorTitle')).toHaveText('WebVTT cue editor')
 await expect(page.locator('label[for="source"]')).toHaveText('Original video source')
 await expect(page.locator('#disclaimer')).toContainText('Export WebVTT before closing')
 await page.locator('#vtt').setInputFiles({name:'bad-en.vtt',mimeType:'text/vtt',buffer:Buffer.from('WEBVTT\n\n00:03:58.000 --> 00:04:02.000\nOutside duration\n')})
 await expect(page.locator('#status')).toContainText('Invalid WebVTT cues')
 await expect(page.locator('.cue-row')).toHaveCount(0)
 await page.locator('#vtt').setInputFiles({name:'empty.vtt',mimeType:'text/vtt',buffer:Buffer.from('WEBVTT\n\n')})
 await expect(page.locator('#status')).toContainText('No caption cues')
 expect(errors).toEqual([])
 expect(remote).toEqual([])
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2)).toBe(true)
 await page.screenshot({path:info.outputPath('osa-v19-private-captions.png'),fullPage:true,animations:'disabled'})
})
