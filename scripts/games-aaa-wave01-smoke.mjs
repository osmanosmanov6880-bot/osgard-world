import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
const root='public/games/';
const html=readFileSync(root+'index.html','utf8');
const css=readFileSync(root+'player-immersive.css','utf8');
const tracker=readFileSync(root+'roadmap/index.html','utf8');
const app=readFileSync(root+'roadmap/roadmap.js','utf8');
const lifecycle=readFileSync(root+'player-lifecycle.js','utf8');
const plan=JSON.parse(readFileSync(root+'aaa-roadmap.v1.json','utf8'));
assert.equal(plan.schemaVersion,1);
assert.equal(plan.waves.length,11);
assert.equal(plan.games.length,22);
assert.equal(new Set(plan.games.map(game=>game.id)).size,22);
assert.equal(new Set(plan.games.map(game=>game.route)).size,22);
assert.equal(plan.waves.filter(w=>w.state==='completed').length,1);
assert.equal(plan.waves.filter(w=>w.state==='in_review').length,1);
for(const game of plan.games)assert.ok(html.includes('data-game="'+game.id+'"'),'Missing game '+game.id);
assert.ok(html.includes('href="/games/roadmap/"'),'Main portal must link roadmap');
assert.ok(html.includes('href="./player-immersive.css"'),'Missing immersive stylesheet');
assert.ok(html.includes('id="player-popout"'),'Missing separate window escape');
assert.ok(html.includes("$('#player-popout').href=url"),'Popout must point to current game');
assert.ok(css.includes('width:calc(100dvw - 24px)')&&css.includes('height:calc(100dvh - 24px)'),'Desktop immersive layout missing');
assert.ok(css.includes('.player-view{')&&css.includes('height:100%')&&css.includes('min-height:0'),'Iframe must fill available flexible player region');
assert.ok(css.includes('@media(max-width:760px)')&&css.includes('width:100dvw;height:100dvh'),'Mobile immersive layout missing');
assert.ok(css.includes('min-height:44px'),'Accessible touch target missing');
assert.ok(tracker.includes('data-wave-filter="completed"')&&tracker.includes('data-game-filter="zion"'),'Interactive filters missing');
assert.ok(app.includes('data.games.length!==22')&&app.includes('renderWaves(data)')&&app.includes('renderGames(data)'),'Tracker must validate and render complete registry');
assert.ok(lifecycle.includes('event.source!==frame.contentWindow'),'Session isolation must be preserved');
for(const game of plan.games)assert.ok(game.reference&&game.emblem&&game.wave&&game.gameplay,'Missing individual creative direction');
assert.ok(existsSync('docs/OSGARD_WORLD_AAA_EXECUTION_ROADMAP.md'),'Missing release acceptance criteria');
console.log('PASS OSGARD AAA WAVE 01: 22 catalogue worlds, 11 evidence-gated waves, immersive desktop/mobile launcher, separate launch, interactive tracker, and session safety');
