import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = path => readFileSync(path, 'utf8')
const mark = read('src/OSAMark.tsx')
const logo = read('src/OsgardLogo.tsx')
const intro = read('src/Preloader.tsx')
const app = read('src/App.tsx')
const home = read('src/OSAIntelligenceHome.tsx')
const tokens = read('src/osa5-brand.css')
const transition = read('public/brand/osa-transition.js')
const icon = read('public/brand/osa-5-mark.svg')
const html = read('index.html')
const skill = read('public/skillcred/index.html')
const games = read('public/games/index.html')
const entertainment = read('public/entertainment/index.html')
const cinema = read('src/OSACinema.tsx')
const main = read('src/main.tsx')

assert.ok(mark.includes('viewBox="0 0 64 64"') && mark.includes('M18 7.5h20.5L52 21'), 'OSA 5.0 vector geometry must be present')
assert.ok(logo.includes("import { OSAMark } from './OSAMark'") && logo.includes('OSA 5.0'), 'OSGARD logo must use the OSA signature')
assert.ok(intro.includes('osgard-preloader-seen-v3') && intro.includes('reduced ? 80 : 910') && intro.includes('if (alreadySeen) return null'), 'Intro must be session-limited, brief and reduced-motion aware')
assert.ok(!intro.includes('Sound on') && !intro.includes('5000'), 'Intro cannot contain fake sound controls or a five-second blocker')
assert.ok(app.includes('className="osgard-world-app"') && app.includes('<OSAMark variant="mark" className="osgard-ecosystem-mark" />'), 'OSGARD portal must carry the shared mark')
assert.ok(home.includes('OSA 5.0') && home.includes('osa-home-art-sequence') && !home.includes('Brain size={20}'), 'OSA Intelligence must use the custom mark and purposeful hero art')
assert.ok(tokens.includes('--osa5-champagne') && tokens.includes('prefers-reduced-motion') && tokens.includes('.osgard-world-app .world-selector button.is-active'), 'Design tokens must include palette profiles, focus and motion')
assert.ok(transition.includes('sessionStorage') && transition.includes('prefers-reduced-motion') && transition.includes("source.relList.contains('external')"), 'Cross-portal transition must be one-shot and motion-aware')
assert.ok(transition.includes('reduced ? 100 : 460'), 'Transition overlay must have a bounded lifetime')
assert.ok(icon.includes('viewBox="0 0 64 64"') && icon.includes('M18 7.5h20.5L52 21'), 'Static icon must share the mark geometry')
assert.ok(html.includes('/brand/osa-5-mark.svg') && html.includes('/brand/osa-transition.js'), 'React entry must load the common favicon and transition')
assert.ok(skill.includes('class="ecosystem-backlink"') && skill.includes('/brand/osa-transition.js'), 'SkillCred must retain its identity and expose an ecosystem return')
assert.ok(games.includes('/brand/osa-5-mark.svg') && games.includes('/brand/osa-transition.js'), 'Game hub must use the common mark and transition')
assert.ok(entertainment.includes('osa5-legacy-brand') && entertainment.includes('/brand/osa-transition.js'), 'Legacy entertainment must remain linked without replacing the catalog')
assert.ok(cinema.includes("import { OSAMark } from './OSAMark'") && cinema.includes("className='cinema-osa-mark'"), 'OSA Original must use the common mark')
assert.ok(main.includes("import './osa5-brand.css'"), 'Shared design system must load after existing styles')
assert.ok(main.includes("if (path === '/') return <><Seo path=\"/\" /><OSAIntelligenceHome /></>"), 'OSA Intelligence root route must remain unchanged')
assert.ok(main.includes("if (path === '/portal') return <><Seo path=\"/portal\" /><App /></>"), 'OSGARD ecosystem must remain available on its current route')
assert.ok(cinema.includes("className='cinema-brand' href='/portal'"), 'Course return route must remain intact')
console.log('PASS OSA 5.0 design contract: shared SVG identity, preserved routes, short intro and bounded portal transitions')
