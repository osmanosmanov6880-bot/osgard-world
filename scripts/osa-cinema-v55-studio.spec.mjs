import { test, expect } from '@playwright/test'

test('V55 studio: real searchable bilingual collection, watchlist, keyboard-safe dossier', async ({page},info)=>{
 const errors=[]
 page.on('pageerror',err=>errors.push(err.message))
 const response=await page.goto('/osa-cinema/studio?lang=ru')
 expect(response?.status()).toBe(200)
 const studio=page.locator('main.osa-studio:not(.osa-film-page)')
 await expect(studio).toBeVisible()
 await expect(studio.locator('.osa-studio-card')).toHaveCount(3)
 await expect(studio.getByRole('heading',{name:'Коллекция студии'})).toBeVisible()
 await studio.getByRole('button',{name:'Фильмы',exact:true}).click()
 await expect(studio.locator('.osa-studio-card')).toHaveCount(1)
 await expect(studio.getByText('НУЛЕВОЕ ОКНО',{exact:true}).first()).toBeVisible()
 await studio.getByRole('button',{name:'Все',exact:true}).click()
 await studio.getByRole('button',{name:'В избранное'}).first().click()
 await studio.getByRole('button',{name:'Избранное',exact:true}).click()
 await expect(studio.locator('.osa-studio-card')).toHaveCount(1)
 await page.reload()
 await studio.getByRole('button',{name:'Избранное',exact:true}).click()
 await expect(studio.locator('.osa-studio-card')).toHaveCount(1)
 await studio.getByRole('button',{name:'Все',exact:true}).click()
 const search=studio.getByRole('textbox',{name:'Поиск проектов'})
 await search.fill('threshold')
 await expect(studio.locator('.osa-studio-card')).toHaveCount(1)
 await search.clear()
 await studio.getByRole('button',{name:'Switch to English'}).click()
 await expect(studio).toHaveAttribute('lang','en')
 await expect(page).toHaveURL(/lang=en/)
 await studio.getByRole('button',{name:'Previz',exact:true}).click()
 await expect(studio.locator('.osa-studio-card')).toHaveCount(1)
 const opener=studio.getByRole('button',{name:'Project details'})
 await opener.click()
 const modal=studio.getByRole('dialog',{name:'THRESHOLD'})
 await expect(modal).toBeVisible()
 await expect(modal.getByRole('button',{name:'Close'})).toBeFocused()
 await page.keyboard.press('Escape')
 await expect(modal).toHaveCount(0)
 await expect(opener).toBeFocused()
 await opener.click()
 await modal.getByRole('link',{name:'Open production dossier'}).click()
 await expect(page.locator('main.osa-film-page[data-project-id="threshold"]')).toBeVisible()
 await expect(page.locator('main.osa-film-page')).toHaveAttribute('data-public-video','blocked')
 await expect(page.locator('video, video source')).toHaveCount(0)
 await expect(page.getByRole('heading',{name:'Not publicly premiered'})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
 expect(errors).toEqual([])
 await page.screenshot({path:info.outputPath('osa-studio-v55-desktop.png'),fullPage:true,animations:'disabled'})
})

test('V55 mobile film dossier, RU/EN switch, release gates, missing-title 404',async ({page},info)=>{
 const errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.setViewportSize({width:390,height:844})
 const response=await page.goto('/osa-cinema/studio/films/zero-window?lang=ru')
 expect(response?.status()).toBe(200)
 const project=page.locator('main.osa-film-page[data-project-id="zero-window"]')
 await expect(project).toBeVisible()
 await expect(project.getByRole('heading',{name:'НУЛЕВОЕ ОКНО'})).toBeVisible()
 await expect(project.locator('.osa-film-gate')).toHaveCount(6)
 await expect(project).toHaveAttribute('data-public-video','blocked')
 await expect(project.locator('video, source[src]')).toHaveCount(0)
 await project.getByRole('button',{name:'Switch to English'}).click()
 await expect(page).toHaveURL(/lang=en/)
 await expect(project.getByRole('heading',{name:'ZERO WINDOW'})).toBeVisible()
 const favorite=project.getByRole('button',{name:'Save'})
 await favorite.click()
 await expect(project.getByRole('button',{name:'Saved'})).toHaveAttribute('aria-pressed','true')
 await page.reload()
 await expect(project.getByRole('button',{name:'Saved'})).toHaveAttribute('aria-pressed','true')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
 await page.screenshot({path:info.outputPath('osa-studio-v55-mobile.png'),fullPage:true,animations:'disabled'})
 await page.goto('/osa-cinema/studio/films/not-a-film?lang=en')
 await expect(page.getByRole('heading',{name:'Project not found'})).toBeVisible()
 expect(errors).toEqual([])
})

