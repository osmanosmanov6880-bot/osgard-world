import { test,expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

const api='/api/core/',pw='test collaboration v62 password 2026'
const random=(prefix)=>prefix+Math.random().toString(36).slice(2,10)
async function register(request,prefix){
 const username=random(prefix)
 const res=await request.post(api+'auth/register',{data:{username,password:pw}})
 expect(res.status()).toBe(200)
 return {...await res.json(),username}
}
const auth=async(page,token)=>page.addInitScript(t=>sessionStorage.setItem('osgard:core-session:v1',t),token)
async function createRoom(page,film='zero-window'){
 await page.goto('/osa-cinema/studio/collaboration?lang=en')
 const root=page.locator('main.osa-collab-page')
 await expect(root.getByRole('heading',{name:'Production coordination.'})).toBeVisible()
 await root.getByRole('combobox',{name:'Film'}).selectOption(film)
 await root.getByRole('textbox',{name:'Workspace title'}).fill('V62 evidence desk '+film)
 await root.getByRole('button',{name:'Create server workspace'}).click()
 await expect(root.getByRole('heading',{name:'V62 evidence desk '+film})).toBeVisible()
 return root
}
test('V62 evidence room cannot be accessed without real Core credentials',async({page,request})=>{
 const unauth=await request.get(api+'cinema/spaces')
 expect(unauth.status()).toBe(401)
 await page.goto('/osa-cinema/studio/collaboration?lang=en')
 await expect(page.locator('main.osa-collab-page')).toHaveAttribute('data-release-state','no-go')
 await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content','noindex,follow')
 await expect(page.getByRole('heading',{name:'Sign in to Core.'})).toBeVisible()
 await expect(page.locator('.osa-evidence-room')).toHaveCount(0)
})
test('V62 real metadata: 2-person review with role isolation, no false legal clearance',async({page,request,context},info)=>{
 const owner=await register(request,'owner62'),peer=await register(request,'peer62'),viewer=await register(request,'viewer62')
 await auth(page,owner.token)
 const root=await createRoom(page)
 await root.getByRole('tab',{name:'Evidence room'}).click()
 const evidence=root.locator('.osa-evidence-room')
 await expect(evidence).toBeVisible()
 await expect(evidence).toHaveAttribute('data-evidence-scope','metadata-only')
 await expect(evidence).toContainText('STRICT NO-GO')
 await expect(evidence.getByText('No actual records match this filter. Nothing is generated automatically.')).toBeVisible()
 await evidence.getByRole('textbox',{name:'Record title'}).fill('Original screenplay document metadata')
 await evidence.getByRole('textbox',{name:'HTTPS source URL (optional)'}).fill('https://example.org/osa-script')
 await evidence.getByRole('textbox',{name:'Description and limitations'}).fill('Declared source URL; real file not downloaded or checked.')
 await evidence.getByRole('button',{name:'Create draft'}).click()
 const item=evidence.locator('.osa-evidence-card',{hasText:'Original screenplay document metadata'})
 await expect(item).toBeVisible()
 await expect(item.locator('.osa-evidence-pill')).toContainText('Draft')
 await item.getByRole('button',{name:'Request review'}).click()
 await expect(item.locator('.osa-evidence-pill')).toContainText('Internal review requested')
 await expect(item).toContainText('Self-review is blocked')
 await root.getByRole('tab',{name:'Team'}).click()
 await root.getByRole('textbox',{name:'Existing account username'}).fill(peer.username)
 await root.getByRole('button',{name:'Save server-side role'}).click()
 await expect(root.locator('.osa-collab-people')).toContainText(peer.username)
 await root.getByRole('textbox',{name:'Existing account username'}).fill(viewer.username)
 await root.getByRole('combobox',{name:'Role'}).selectOption('viewer')
 await root.getByRole('button',{name:'Save server-side role'}).click()
 await expect(root.locator('.osa-collab-people')).toContainText(viewer.username)
 const peerPage=await context.newPage();await auth(peerPage,peer.token)
 await peerPage.goto('/osa-cinema/studio/collaboration?lang=en')
 await peerPage.getByRole('tab',{name:'Evidence room'}).click()
 const peerRoom=peerPage.locator('.osa-evidence-room')
 await expect(peerRoom.locator('.osa-evidence-card')).toHaveCount(1)
 await peerRoom.getByRole('button',{name:'Review entry'}).click()
 await peerRoom.getByRole('combobox',{name:'Decision'}).selectOption('internally_reviewed')
 await peerRoom.getByRole('textbox',{name:'Reason (20–1000 characters)'}).fill('Internal peer review of metadata only; not a file audit or film rights clearance.')
 await peerRoom.getByRole('button',{name:'Save review'}).click()
 await expect(peerRoom.locator('.osa-evidence-pill')).toContainText('Internally reviewed')
 await expect(peerRoom.locator('.osa-evidence-review-history')).toContainText(peer.username)
 const viewerPage=await context.newPage();await auth(viewerPage,viewer.token)
 await viewerPage.goto('/osa-cinema/studio/collaboration?lang=en')
 await viewerPage.getByRole('tab',{name:'Evidence room'}).click()
 await expect(viewerPage.locator('.osa-evidence-card')).toHaveCount(1)
 await expect(viewerPage.locator('.osa-evidence-create')).toHaveCount(0)
 await expect(viewerPage.locator('.osa-evidence-actions button')).toHaveCount(0)
 const spaces=await request.get(api+'cinema/spaces',{headers:{Authorization:'Bearer '+owner.token}})
 const wid=(await spaces.json()).spaces[0].id
 const ledger=await request.get(api+'cinema/spaces/'+wid+'/evidence',{headers:{Authorization:'Bearer '+owner.token}})
 expect(ledger.status()).toBe(200)
 expect(ledger.headers()['cache-control']).toContain('no-store')
 const saved=await ledger.json()
 expect(saved.evidence[0].state).toBe('internally_reviewed')
 expect(saved.evidence[0].checksumVerifiedByServer).toBe(false)
 expect(saved.rightsIndependentlyVerified).toBe(false)
 expect(saved.releaseAuthorized).toBe(false)
 expect(saved.publicVideoUrl).toBe(null)
 expect(saved.evidence[0].reviews[0].reviewer).toBe(peer.username)
 await page.reload()
 await root.getByRole('tab',{name:'Evidence room'}).click()
 await expect(evidence.locator('.osa-evidence-pill')).toContainText('Internally reviewed')
 const [dl]=await Promise.all([page.waitForEvent('download'),evidence.getByRole('button',{name:'Export metadata'}).click()])
 const exported=JSON.parse(readFileSync(await dl.path(),'utf8'))
 expect(exported.sourcesFetched).toBe(false)
 expect(exported.filesUploaded).toBe(false)
 expect(exported.publicReleaseAuthorized).toBe(false)
 expect(exported.evidence).toHaveLength(1)
 expect(JSON.stringify(exported)).not.toContain(owner.token)
 await page.screenshot({path:info.outputPath('osa-v62-peer-review-desktop.png'),fullPage:true,animations:'disabled'})
})
