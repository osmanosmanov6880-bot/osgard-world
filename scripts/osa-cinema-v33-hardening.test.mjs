import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtemp, mkdir, chmod, readdir, readFile, rm, stat, symlink, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { createHash } from 'node:crypto'
import { preparePrivateWorkspace, inspectOwnerWorkspace, savePrivateDiagnostic } from './osa-cinema-v32-first-run.mjs'

const sha = data => createHash('sha256').update(data).digest('hex')
async function missing(path){await assert.rejects(stat(path),{code:'ENOENT'})}

// No real films or real publisher permissions are generated by any test.
test('V33 transactional workspace: reject every existing hazard before mutating anything',async t=>{
 const base=await mkdtemp(join(tmpdir(),'osa-v33-preflight-'))
 try{
   await t.test('existing masters symlink blocks creating new reports and captions',async()=>{
     if(process.platform==='win32')return // Windows symlink creation may require elevated privilege.
     const film=join(base,'film-linked-masters'),reports=join(base,'no-reports-created')
     await mkdir(film,{mode:0o700})
     const outside=join(base,'outside');await mkdir(outside,{mode:0o700})
     await symlink(outside,join(film,'masters'),'dir')
     await assert.rejects(preparePrivateWorkspace({root:film,reportsRoot:reports}),/символическая ссылка/)
     await missing(reports);await missing(join(film,'captions'))
     assert.deepEqual(await readdir(outside),[])
   })
   await t.test('existing captions is a file, not a directory: stop with no new folders',async()=>{
     const film=join(base,'film-invalid-captions'),reports=join(base,'no-evidence-created')
     await mkdir(film,{mode:0o700})
     await writeFile(join(film,'captions'),'NOT A DIRECTORY')
     await assert.rejects(preparePrivateWorkspace({root:film,reportsRoot:reports}),/не является папкой/)
     await missing(reports);await missing(join(film,'masters'))
   })
   await t.test('existing overly permissive masters blocks new reports (POSIX)',async()=>{
     if(process.platform==='win32')return
     const film=join(base,'film-insecure-master'),reports=join(base,'no-reports-from-insecure')
     await mkdir(film,{mode:0o700});await mkdir(join(film,'masters'),{mode:0o755})
     await chmod(join(film,'masters'),0o755)
     await assert.rejects(preparePrivateWorkspace({root:film,reportsRoot:reports}),/chmod 700/)
     await missing(reports);await missing(join(film,'captions'))
   })
   await t.test('rollback removes empty new film folders if reports path creation fails',async()=>{
     if(process.platform==='win32')return
     const film=join(base,'film-to-rollback'),locked=join(base,'owner-no-write'),reports=join(locked,'receipts')
     await mkdir(locked,{mode:0o500});await chmod(locked,0o500)
     // A root-running CI service can bypass DAC denial; this is a test of
     // filesystem semantics only for a non-root owner.
     try{
       if(process.getuid?.()===0)return
       await assert.rejects(preparePrivateWorkspace({root:film,reportsRoot:reports}),/EACCES|EPERM|permission denied/i)
       await missing(film);await missing(reports)
     }finally{await chmod(locked,0o700)}
   })
   await t.test('valid partial workspace is completed but no video, VTT or fake rights are created',async()=>{
     const film=join(base,'safe-film'),reports=join(base,'safe-reports')
     await mkdir(film,{mode:0o700})
     await mkdir(join(film,'masters'),{mode:0o700})
     const prepared=await preparePrivateWorkspace({root:film,reportsRoot:reports})
     assert.equal(prepared.publicationAuthorized,false)
     assert.equal(prepared.rightsCleared,false)
     assert.equal(prepared.paidCheckoutEnabled,false)
     assert.equal(prepared.expected.length,8)
     assert.deepEqual(await readdir(join(film,'masters')),[])
     assert.deepEqual(await readdir(join(film,'captions')),[])
     assert.deepEqual(await readdir(reports),[])
     const d=await inspectOwnerWorkspace({root:film,reportsRoot:reports,checkFFmpeg:false})
     assert.equal(d.readyForPrivateTechnicalPreflight,false)
     assert.equal(d.releaseDecision,'NO_GO')
     assert.equal(d.presentCount,0)
   })
 }finally{await rm(base,{recursive:true,force:true})}
})

test('V33 private diagnostic: all release flags fail-closed and a missing sidecar is rolled back',async t=>{
 const base=await mkdtemp(join(tmpdir(),'osa-v33-pair-'))
 const film=join(base,'film'),reports=join(base,'reports')
 try{
   await preparePrivateWorkspace({root:film,reportsRoot:reports})
   const d=await inspectOwnerWorkspace({root:film,reportsRoot:reports,checkFFmpeg:false})
   for(const [flag,value] of [['publicationAuthorized',true],['rightsCleared',true],['paidCheckoutEnabled',true],['releaseDecision','GO']]){
     await t.test('forged '+flag+' is refused',async()=>{
       await assert.rejects(savePrivateDiagnostic({diagnostic:{...d,[flag]:value},reportsRoot:reports}),/Refuse/)
       assert.deepEqual(await readdir(reports),[])
     })
   }
   await t.test('simulated second-write failure leaves neither orphan JSON nor SHA file',async()=>{
     const writer=async (path,...args)=>{
       if(path.endsWith('.sha256'))throw Error('simulated disk full on second file')
       return writeFile(path,...args)
     }
     await assert.rejects(savePrivateDiagnostic({diagnostic:d,reportsRoot:reports,writeFileImpl:writer}),/simulated disk full/)
     assert.deepEqual(await readdir(reports),[])
   })
   await t.test('success writes exactly two private files with independently verifiable content',async()=>{
     const pair=await savePrivateDiagnostic({diagnostic:d,reportsRoot:reports})
     const files=await readdir(reports);assert.equal(files.length,2)
     const json=await readFile(join(reports,pair.reportName))
     assert.equal(sha(json),pair.sha256)
     const sidecar=await readFile(join(reports,pair.reportName.replace(/\.json$/,'.sha256')),'utf8')
     assert.equal(sidecar,`${pair.sha256}  ${pair.reportName}\n`)
     assert.equal(JSON.parse(json).paidCheckoutEnabled,false)
     if(process.platform!=='win32')for(const name of files)assert.equal((await stat(join(reports,name))).mode&0o077,0)
   })
 }finally{await rm(base,{recursive:true,force:true})}
})
