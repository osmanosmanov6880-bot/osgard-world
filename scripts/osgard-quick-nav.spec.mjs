import { expect, test } from '@playwright/test'

const trigger = page => page.getByRole('button', { name: 'Быстрый переход по разделам OSGARD' })
const quickDialog = page => page.getByRole('dialog', { name: 'Куда перейти?' })

test('Global OSGARD Navigator opens a real Academy route and restores keyboard focus', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await trigger(page).click()
  await expect(quickDialog(page)).toBeVisible()
  const search = quickDialog(page).getByRole('combobox', { name: 'Поиск по разделам OSGARD' })
  await expect(search).toBeFocused()
  await search.fill('академия')
  await expect(quickDialog(page).getByRole('option')).toHaveCount(1)
  await expect(quickDialog(page).getByRole('option').first()).toHaveAttribute('href', '/academy')
  await search.press('Enter')
  await expect(page).toHaveURL(/\/academy\/?$/)
  await expect(page.locator('.academy-learning-console')).toBeVisible()
  await expect(quickDialog(page)).toHaveCount(0)
  await page.keyboard.press('Control+k')
  await expect(quickDialog(page)).toBeVisible()
  await expect(quickDialog(page).getByRole('combobox')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(quickDialog(page)).toHaveCount(0)
  await expect(trigger(page)).toBeFocused()
  expect(errors).toEqual([])
})

test('Navigator opens a real Development section, keeps only per-tab recent shortcuts and clears them', async ({ page }) => {
  await page.goto('/intelligence')
  await page.keyboard.press('Control+k')
  const search = quickDialog(page).getByRole('combobox')
  await search.fill('TEDES')
  await expect(quickDialog(page).getByRole('option')).toHaveCount(1)
  await expect(quickDialog(page).getByRole('option')).toHaveAttribute('href', '/development#cases')
  await search.press('Enter')
  await expect(page).toHaveURL(/\/development#cases$/)
  await expect(page.locator('.signature-showcase')).toBeVisible()
  await expect(quickDialog(page)).toHaveCount(0)
  const stored = await page.evaluate(() => JSON.parse(sessionStorage.getItem('osgard:quick-nav:session') || '[]'))
  expect(stored[0]).toBe('cases')
  await trigger(page).click()
  await expect(quickDialog(page).locator('[data-command-id="cases"]')).toContainText('НЕДАВНО')
  await quickDialog(page).getByRole('button', { name: 'Очистить недавние' }).click()
  expect(await page.evaluate(() => sessionStorage.getItem('osgard:quick-nav:session'))).toBe(null)
  await expect(quickDialog(page).locator('[data-command-id="cases"]')).not.toContainText('НЕДАВНО')
  await page.keyboard.press('Tab')
  expect(await page.evaluate(() => document.activeElement?.closest('[role="dialog"]') !== null)).toBe(true)
  await page.keyboard.press('Escape')
  await expect(trigger(page)).toBeFocused()
})

test('Navigator fits on mobile and opens real seven-game archive without replacing full Play', async ({ page }) => {
  await page.goto('/play')
  await trigger(page).click()
  const dialog = quickDialog(page)
  await expect(dialog).toBeVisible()
  const size = await dialog.evaluate(element => ({ left: element.getBoundingClientRect().left, right: element.getBoundingClientRect().right }))
  const viewport = page.viewportSize()
  expect(viewport).not.toBeNull()
  expect(size.left).toBeGreaterThanOrEqual(-1)
  expect(size.right).toBeLessThanOrEqual(viewport.width + 1)
  await dialog.getByRole('combobox').fill('архив')
  const option = dialog.getByRole('option')
  await expect(option).toHaveCount(1)
  await expect(option).toHaveAttribute('href', '/entertainment/archive/')
  await option.click()
  await expect(page).toHaveURL(/\/entertainment\/archive\/?$/)
  await expect(page.locator('body.entertainment-premium')).toBeVisible()
  await expect(page.locator('.grid .card')).toHaveCount(7)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
