import { test, expect } from '@playwright/test'

test('WAVE 03: remember last game safely, show true controls, clear remembered launch',async ({page})=>{
  test.setTimeout(60_000)
  await page.goto('/games/',{waitUntil:'domcontentloaded'})
  await expect(page.locator('#games-grid article.card[data-game]')).toHaveCount(22)
  await expect(page.locator('#last-session')).toBeHidden()
  await page.locator('#games-grid article.card[data-game="time"] a.play-link').click()
  await expect(page.locator('#player-dialog')).toBeVisible()
  await page.locator('#player-help-toggle').click()
  await expect(page.locator('#player-help-panel')).toBeVisible()
  await expect(page.locator('#player-help-toggle')).toHaveAttribute('aria-expanded','true')
  await expect(page.locator('#player-help-panel')).toContainText('Кнопки действий')
  await expect(page.locator('#player-help-panel')).toContainText('Локальное сохранение в браузере')
  const bounds=await page.locator('#player-help-panel').evaluate(node=>({right:node.getBoundingClientRect().right,width:node.getBoundingClientRect().width}))
  expect(bounds.right).toBeLessThanOrEqual(page.viewportSize().width+2)
  expect(bounds.width).toBeGreaterThan(210)
  await page.locator('#player-help-toggle').click()
  await expect(page.locator('#player-help-panel')).toBeHidden()
  await page.locator('#player-close').click()
  await expect(page.locator('#player-dialog')).not.toBeVisible()
  await page.reload({waitUntil:'domcontentloaded'})
  await expect(page.locator('#last-session')).toBeVisible()
  await expect(page.locator('#last-session-game')).toContainText('Империя времени')
  await expect(page.locator('#last-session-link')).toHaveAttribute('href',/\/games\/time/)
  const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('osgard.games.last-world.v1')))
  expect(stored.version).toBe(1)
  expect(stored.id).toBe('time')
  expect(Object.keys(stored).sort()).toEqual(['id','openedAt','version'])
  await page.locator('#last-session-clear').click()
  await expect(page.locator('#last-session')).toBeHidden()
  expect(await page.evaluate(()=>localStorage.getItem('osgard.games.last-world.v1'))).toBeNull()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
})

test('WAVE 03: corrupt local records cannot redirect, offline reminder is nonblocking',async({page,context})=>{
  await page.goto('/games/',{waitUntil:'domcontentloaded'})
  await page.evaluate(()=>localStorage.setItem('osgard.games.last-world.v1',JSON.stringify({version:1,id:'other-domain',openedAt:Date.now(),url:'https://evil.example'})))
  await page.reload({waitUntil:'domcontentloaded'})
  await expect(page.locator('#last-session')).toBeHidden()
  await context.setOffline(true)
  await expect(page.locator('#player-connection-status')).toBeVisible()
  await expect(page.locator('#player-connection-status')).toContainText('Соединение')
  await context.setOffline(false)
  await expect(page.locator('#player-connection-status')).toBeHidden()
  await expect(page.locator('#game-search')).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
})
