import { test,expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import { createHash,randomUUID } from 'node:crypto'

const api='/api/core/',password='safe browser binary vault 2026'
const pdf=Buffer.from('%PDF-1.7\n1 0 obj <</Type/Catalog>>\nendobj\n%%EOF\n')
const mp4=Buffer.from([0,0,0,24,...Buffer.from('ftypisom'),0,0,0,0,...Buffer.from('isomiso2')])
const id=(prefix)=>prefix+Math.random().toString(36).slice(2,10)
async function register(request,prefix){
 const username=id(prefix)
 const r=await request.post(api+'auth/register',{data:{username,password}})
 expect(r.status()).toBe(200)
 return {...await r.json(),username}
}
async function session(page,token){await page.addInitScript(t=>sessionStorage.setItem('osgard:core-session:v1',t),token)}
async function newRoom(page,film='zero-window'){
 await page.goto('/osa-cinema/studio/collaboration?lang=en')
 const app=page.locator('main.osa-collab-page')
 await expect(app.getByRole('heading',{name:'Production coordination.'})).toBeVisible()
 await app.getByRole('combobox',{name:'Film'}).selectOption(film)
 await app.getByRole('textbox',{name:'Workspace title'}).fill('Vault V63 '+film)
 await app.getByRole('button',{name:'Create server workspace'}).click()
 await expect(app.getByRole('heading',{name:'Vault V63 '+film})).toBeVisible()
 return app
}
async function openVault(app){
 await app.getByRole('tab',{name:'File vault'}).click()
 await expect(app.locator('.osa-vault')).toBeVisible()
 await expect(app.locator('.osa-vault')).toHaveAttribute('data-private-vault','binary-sqlite')
}
test('V63 private byte vault enforces actual Core sign-in and no fake files',async({page,request})=>{
 expect((await request.get(api+'cinema/spaces')).status()).toBe(401)
 await page.goto('/osa-cinema/studio/collaboration?lang=en')
 await expect(page.getByRole('heading',{name:'Sign in to Core.'})).toBeVisible()
 await expect(page.locator('.osa-vault')).toHaveCount(0)
 await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content','noindex,follow')
})
test('V63 real binary upload, sha256 browser download, viewer access and revoke',async({page,request,context},info)=>{
 const owner=await register(request,'own63'),viewer=await register(request,'view63')
 await session(page,owner.token)
 const app=await newRoom(page)
 await openVault(app)
 const vault=app.locator('.osa-vault')
 await expect(vault).toContainText('No files uploaded.')
 await vault.locator('input[type=file]').setInputFiles({name:'screenplay.pdf',mimeType:'application/pdf',buffer:pdf})
 await vault.getByRole('button',{name:'Store actual bytes in Core'}).click()
 await expect(vault.locator('.osa-vault-asset')).toHaveCount(1)
 const item=vault.locator('.osa-vault-asset')
 await expect(item).toContainText('screenplay.pdf')
 const hash=createHash('sha256').update(pdf).digest('hex')
 await item.locator('summary').click()
 await expect(item.locator('code')).toHaveText(hash)
 const [download]=await Promise.all([page.waitForEvent('download'),item.getByRole('button',{name:'Verify & download'}).click()])
 expect(download.suggestedFilename()).toBe('screenplay.pdf')
 expect(readFileSync(await download.path()).equals(pdf)).toBe(true)
 await page.screenshot({path:info.outputPath('osa-v63-vault-desktop.png'),fullPage:true,animations:'disabled'})
 const spaces=await request.get(api+'cinema/spaces',{headers:{Authorization:'Bearer '+owner.token}})
 const workspaceId=(await spaces.json()).spaces[0].id
 const endpoint=api+'cinema/spaces/'+workspaceId+'/vault'
 const raw=await request.get(endpoint,{headers:{Authorization:'Bearer '+owner.token}})
 expect(raw.status()).toBe(200)
 const record=await raw.json()
 expect(record.assets[0].actualSha256).toBe(hash)
 expect(record.assets[0].checksumComputedFromBytes).toBe(true)
 expect(record.assets[0].malwareScanned).toBe(false)
 expect(record.encryptionAtRest).toBe(false)
 expect(record.publicStreamingEnabled).toBe(false)
 expect(record.publicVideoUrl).toBe(null)
 const assetId=record.assets[0].id
 const anon=await request.get(endpoint+'/'+assetId+'/download')
 expect(anon.status()).toBe(401)
 await app.getByRole('tab',{name:'Team'}).click()
 await app.getByRole('textbox',{name:'Existing account username'}).fill(viewer.username)
 await app.getByRole('combobox',{name:'Role'}).selectOption('viewer')
 await app.getByRole('button',{name:'Save server-side role'}).click()
 await expect(app.locator('.osa-collab-people')).toContainText(viewer.username)
 const other=await context.newPage()
 await session(other,viewer.token)
 await other.goto('/osa-cinema/studio/collaboration?lang=en')
 await openVault(other.locator('main.osa-collab-page'))
 await expect(other.locator('.osa-vault-asset')).toHaveCount(1)
 await expect(other.locator('.osa-vault-form')).toHaveCount(0)
 await expect(other.locator('.osa-vault-remove')).toHaveCount(0)
 const [viewerDownload]=await Promise.all([other.waitForEvent('download'),other.getByRole('button',{name:'Verify & download'}).click()])
 expect(readFileSync(await viewerDownload.path()).equals(pdf)).toBe(true)
 await page.screenshot({path:info.outputPath('osa-v63-team-access-desktop.png'),fullPage:true,animations:'disabled'})
 await app.getByRole('tab',{name:'Team'}).click()
 await app.locator('.osa-collab-people').getByRole('button',{name:'Remove'}).click()
 await app.locator('.osa-collab-people').getByRole('button',{name:'Confirm removal'}).click()
 await expect(app.locator('.osa-collab-people')).not.toContainText(viewer.username)
 const denied=await request.get(endpoint+'/'+assetId+'/download',{headers:{Authorization:'Bearer '+viewer.token}})
 expect(denied.status()).toBe(404)
 await openVault(app)
 await vault.getByRole('button',{name:'Delete',exact:true}).click()
 await vault.getByRole('button',{name:'Confirm deletion'}).click()
 await expect(vault.locator('.osa-vault-asset')).toHaveCount(0)
 const gone=await request.get(endpoint+'/'+assetId+'/download',{headers:{Authorization:'Bearer '+owner.token}})
 expect(gone.status()).toBe(404)
})
