import { test, expect } from '@playwright/test'

const ROOT='https://osgard.world/osa-cinema/premiere/'
const READY=12000

test('real public cinema: desktop MP4, seek, languages, VTT and trailer',async({page})=>{
  await page.setViewportSize({width:1536,height:960})
  const response=await page.goto(ROOT,{waitUntil:'domcontentloaded'})
  expect(response?.status()).toBe(200)
  await expect(page.locator('h1')).toContainText('BEYOND')
  await expect(page.locator('#film')).toBeVisible()
  await expect.poll(()=>page.locator('#film').evaluate(v=>v.readyState),{timeout:READY}).toBeGreaterThanOrEqual(1)
  const duration=await page.locator('#film').evaluate(v=>v.duration)
  expect(duration).toBeGreaterThan(237)
  expect(duration).toBeLessThan(241)
  await page.locator('#film').evaluate(async v=>{v.muted=true;await v.play()})
  await expect.poll(()=>page.locator('#film').evaluate(v=>v.currentTime),{timeout:READY}).toBeGreaterThan(.1)
  await page.locator('.chapter[data-time="81"]').click()
  await expect.poll(()=>page.locator('#film').evaluate(v=>v.currentTime),{timeout:READY}).toBeGreaterThan(79)
  await page.locator('#en').click()
  await expect(page.locator('html')).toHaveAttribute('lang','en')
  await expect.poll(()=>page.locator('#film source').getAttribute('src')).toContain('directors-en.mp4')
  await expect.poll(()=>page.locator('#film track').count()).toBe(1)
  await expect.poll(()=>page.locator('#film').evaluate(v=>v.readyState),{timeout:READY}).toBeGreaterThanOrEqual(1)
  await page.locator('#captions').click()
  await expect(page.locator('#captions')).toHaveAttribute('aria-pressed','false')
  await page.locator('#captions').click()
  await expect(page.locator('#captions')).toHaveAttribute('aria-pressed','true')
  await page.locator('#preview').click()
  await expect.poll(()=>page.locator('#film').evaluate(v=>v.duration),{timeout:READY}).toBeGreaterThan(43)
  await expect.poll(()=>page.locator('#film').evaluate(v=>v.duration),{timeout:READY}).toBeLessThan(47)
  expect(await page.locator('#film').evaluate(v=>v.error)).toBeNull()
})

test('real public cinema: mobile 390px RU/EN playback and no horizontal overflow',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  const response=await page.goto(ROOT+'?lang=ru&edition=directors',{waitUntil:'domcontentloaded'})
  expect(response?.status()).toBe(200)
  await expect(page.locator('html')).toHaveAttribute('lang','ru')
  await expect(page.locator('#film')).toBeVisible()
  await expect.poll(()=>page.locator('#film').evaluate(v=>v.readyState),{timeout:READY}).toBeGreaterThanOrEqual(1)
  await page.locator('#film').evaluate(async v=>{v.muted=true;await v.play()})
  await expect.poll(()=>page.locator('#film').evaluate(v=>v.currentTime),{timeout:READY}).toBeGreaterThan(.1)
  await expect(page.locator('#film track')).toHaveAttribute('srclang','ru')
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth)
  expect(overflow).toBeLessThanOrEqual(2)
  await page.locator('#en').click()
  await expect(page.locator('html')).toHaveAttribute('lang','en')
  await expect.poll(()=>page.locator('#film source').getAttribute('src')).toContain('directors-en.mp4')
})
