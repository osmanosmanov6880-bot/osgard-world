import { test, expect } from '@playwright/test'

test('OSGARD World index searches, filters and opens six real destinations', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const index = page.locator('#ecosystem')
  await expect(index.getByRole('heading', { name: /Найдите то,/ })).toBeVisible()
  await expect(index.locator('.ecosystem-index-card')).toHaveCount(6)
  await expect(index.getByRole('link', { name: /OSA Intelligence/ })).toHaveAttribute('href', '/intelligence')
  await expect(index.getByRole('link', { name: /OSA Academy/ })).toHaveAttribute('href', '/academy')
  await expect(index.getByRole('link', { name: /OSGARD Play/ })).toHaveAttribute('href', '/play')
  await expect(index.getByRole('link', { name: /Entertainment/ })).toHaveAttribute('href', '/entertainment/archive/')
  await expect(index.getByRole('link', { name: /Development/ })).toHaveAttribute('href', '/development')
  await expect(index.getByRole('link', { name: /Project Studio/ })).toHaveAttribute('href', '/learning/project')
  await index.getByRole('button', { name: 'Играть', exact: true }).click()
  await expect(index.locator('.ecosystem-index-card')).toHaveCount(2)
  await expect(index.getByRole('button', { name: 'Играть', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await index.getByRole('button', { name: 'Все направления' }).click()
  const search = index.getByRole('searchbox', { name: 'Поиск по экосистеме' })
  await search.fill('TEDES')
  await expect(index.locator('.ecosystem-index-card')).toHaveCount(1)
  await expect(index.getByRole('link', { name: /Development/ })).toHaveAttribute('href', '/development')
  await search.fill('несуществующее направление xxx')
  await expect(index.locator('.ecosystem-index-card')).toHaveCount(0)
  await expect(index.getByText('По этому запросу ничего не найдено.')).toBeVisible()
  await index.getByRole('button', { name: 'Показать все' }).click()
  await expect(index.locator('.ecosystem-index-card')).toHaveCount(6)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  expect(errors).toEqual([])
})

test('OSGARD World remembers the last visited product only in this browser and can clear it', async ({ page }) => {
  await page.goto('/')
  const index = page.locator('#ecosystem')
  await expect(index.locator('.ecosystem-index-recent')).toHaveCount(0)
  await index.getByRole('link', { name: /OSA Academy/ }).click()
  await expect(page).toHaveURL(/\/academy\/?$/)
  await page.goto('/')
  const recent = page.locator('#ecosystem .ecosystem-index-recent')
  await expect(recent).toBeVisible()
  await expect(recent).toContainText('OSA Academy')
  await expect(recent.getByRole('link', { name: /Открыть снова/ })).toHaveAttribute('href', '/academy')
  await recent.getByRole('button', { name: 'Очистить историю направления' }).click()
  await expect(recent).toHaveCount(0)
  await page.reload()
  await expect(page.locator('#ecosystem .ecosystem-index-recent')).toHaveCount(0)
  expect(await page.evaluate(() => localStorage.getItem('osgard:recent-destination:v1'))).toBeNull()
})

test('OSGARD World filters are fully keyboard-operable with stable layout', async ({ page }) => {
  await page.goto('/')
  const index = page.locator('#ecosystem')
  const filter = index.getByRole('button', { name: 'Создавать' })
  await filter.focus()
  await expect(filter).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(filter).toHaveAttribute('aria-pressed', 'true')
  await expect(index.locator('.ecosystem-index-card')).toHaveCount(2)
  const search = index.getByRole('searchbox', { name: 'Поиск по экосистеме' })
  await search.focus()
  await page.keyboard.type('project')
  await expect(index.locator('.ecosystem-index-card')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
