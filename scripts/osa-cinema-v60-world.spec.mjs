import { test,expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

test('V60 bilingual public pressroom serves real static source-derived press downloads',async ({page,request},info)=>{
 const errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 const response=await page.goto('/osa-cinema/studio/press?lang=en')
 expect(response.status()).toBe(200)
 const room=page.locator('main.osa-press-page')
 await expect(room).toBeVisible()
 await expect(room).toHaveAttribute('data-public-film-premiere','false')
 await expect(room.getByRole('heading',{name:'STORIES. NOT HYPE.'})).toBeVisible()
 await expect(room.locator('.osa-press-project')).toHaveCount(3)
 await expect(room.locator('.osa-press-gate-denied')).toHaveCount(2)
 await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content','index,follow')
 const api=await request.get('/osa-cinema/studio/press/press.v1.json')
 expect(api.status()).toBe(200)
 expect(api.headers()['content-type']).toContain('application/json')
 const manifest=await api.json()
 expect(manifest.schema).toBe('OSA_CINEMA_WORLD_PRESS_V1')
 expect(manifest.publicPremiereAuthorized).toBe(false)
 expect(manifest.factualProduction.liveActionScenesFilmed).toBe(0)
 expect(manifest.projects).toHaveLength(3)
 expect(manifest.projects.every(p=>p.playbackUrl===null)).toBe(true)
 const [download]=await Promise.all([page.waitForEvent('download'),room.locator('a[download="OSA_CINEMA_press_EN.txt"]').click()])
 expect(download.suggestedFilename()).toBe('OSA_CINEMA_press_EN.txt')
 expect(readFileSync(await download.path(),'utf8')).toContain('PUBLIC RELEASE: NO FILM PREMIERE')
 await room.getByRole('button',{name:'Переключить на русский'}).click()
 await expect(room).toHaveAttribute('lang','ru')
 await expect(room.getByRole('heading',{name:'ИСТОРИИ. БЕЗ ВЫМЫСЛОВ.'})).toBeVisible()
 await page.screenshot({path:info.outputPath('osa-v60-press-desktop.png'),fullPage:true,animations:'disabled'})
 expect(errors).toEqual([])
})

test('V60 distribution desk: real local notes, backup, false rights rejection and cross-tab updates',async ({page,context},info)=>{
 await page.goto('/osa-cinema/studio/distribution?lang=en')
 const desk=page.locator('main.osa-distribution-page')
 await expect(desk).toBeVisible()
 await expect(desk).toHaveAttribute('data-public-release','no-go')
 await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content','noindex,follow')
 await expect(desk.locator('.osa-distribution-overview-no')).toContainText('NO-GO')
 await expect(desk.locator('.osa-distribution-gate')).toHaveCount(8)
 const first=desk.locator('.osa-distribution-gate').first()
 await first.getByRole('combobox',{name:/Preparation status:/}).selectOption('review_requested')
 await first.getByRole('textbox',{name:/Planning notes/}).fill('Request an independent evidence check before filming.')
 await first.getByRole('button',{name:'Save local note'}).click()
 await expect(desk.getByRole('status')).toContainText('Actual release status remains unchanged')
 await expect(desk.locator('.osa-distribution-overview-no')).toContainText('NO-GO')
 const second=await context.newPage()
 await second.goto('/osa-cinema/studio/distribution?lang=en')
 await expect(second.locator('.osa-distribution-gate').first().getByRole('combobox',{name:/Preparation status:/})).toHaveValue('review_requested')
 const [backup]=await Promise.all([page.waitForEvent('download'),desk.getByRole('button',{name:'Export JSON'}).click()])
 const original=readFileSync(await backup.path(),'utf8')
 const packet=JSON.parse(original)
 expect(packet.schema).toBe('OSA_CINEMA_DISTRIBUTION_NOTES_V1')
 expect(packet.releaseAuthorized).toBe(false)
 expect(packet.publicVideoUrl).toBe(null)
 expect(packet.items).toHaveLength(1)
 await desk.getByRole('button',{name:'Clear notes'}).click()
 await desk.getByRole('button',{name:'Confirm deletion'}).click()
 await expect(first.getByRole('combobox',{name:/Preparation status:/})).toHaveValue('not_started')
 await desk.locator('#osa-release-import').setInputFiles({name:'valid.json',mimeType:'application/json',buffer:Buffer.from(original)})
 await expect(first.getByRole('combobox',{name:/Preparation status:/})).toHaveValue('review_requested')
 const forged=JSON.stringify({...packet,releaseAuthorized:true})
 await desk.locator('#osa-release-import').setInputFiles({name:'forged.json',mimeType:'application/json',buffer:Buffer.from(forged)})
 await expect(desk.getByRole('alert')).toContainText('Invalid backup')
 await expect(first.getByRole('combobox',{name:/Preparation status:/})).toHaveValue('review_requested')
 await desk.locator('.osa-distribution-selector button').nth(1).click()
 await expect(desk.locator('.osa-distribution-gate')).toHaveCount(5)
 await desk.locator('#osa-release-import').setInputFiles({name:'wrong-project.json',mimeType:'application/json',buffer:Buffer.from(original)})
 await expect(desk.getByRole('alert')).toContainText('wrong project')
 await expect(desk.locator('.osa-distribution-overview-no')).toContainText('NO-GO')
 await page.setViewportSize({width:320,height:740})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
 await page.screenshot({path:info.outputPath('osa-v60-distribution-mobile-320.png'),fullPage:true,animations:'disabled'})
})

