import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

test('V58 private cinema library: save, export, clear, restore and cross-tab persistence',async ({page,context},info)=>{
 const errors=[]
 page.on('pageerror',err=>errors.push(err.message))
 await page.goto('/osa-cinema/studio?lang=en')
 await expect(page.locator('main.osa-studio')).toBeVisible()
 await page.getByRole('button',{name:'Add to favorites'}).first().click()
 const libraryLink=page.locator('.osa-studio-hero-cta a[href^="/osa-cinema/studio/library"]')
 await libraryLink.click()
 const library=page.locator('main.osa-library-page')
 await expect(library).toBeVisible()
 await expect(library).toHaveAttribute('lang','en')
 await expect(library.locator('.osa-library-item')).toHaveCount(1)
 await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content','noindex,follow')
 const [download]=await Promise.all([page.waitForEvent('download'),library.getByRole('button',{name:/Export JSON/}).click()])
 expect(download.suggestedFilename()).toBe('OSA-CINEMA-watchlist-v1.json')
 const backup=readFileSync(await download.path(),'utf8')
 const saved=JSON.parse(backup)
 expect(saved.schema).toBe('OSA_CINEMA_WATCHLIST_V1')
 expect(saved.storage).toBe('local_device_only')
 expect(saved.favorites).toEqual(['the-next-human'])
 await library.getByRole('button',{name:'Clear collection'}).click()
 await library.getByRole('button',{name:'Confirm clear'}).click()
 await expect(library.locator('.osa-library-item')).toHaveCount(0)
 await expect(library.getByRole('heading',{name:'Nothing saved yet.'})).toBeVisible()
 await library.locator('#osa-library-json').setInputFiles({name:'watchlist.json',mimeType:'application/json',buffer:Buffer.from(backup)})
 await expect(library.locator('.osa-library-item')).toHaveCount(1)
 await expect(library.getByRole('status').filter({hasText:'Collection restored'})).toBeVisible()
 const invalid=JSON.stringify({...saved,favorites:['unknown-film-id']})
 await library.locator('#osa-library-json').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from(invalid)})
 await expect(library.getByRole('alert')).toContainText('Invalid JSON backup')
 await expect(library.locator('.osa-library-item')).toHaveCount(1)
 const second=await context.newPage()
 await second.goto('/osa-cinema/studio/library?lang=en')
 await expect(second.locator('.osa-library-item')).toHaveCount(1)
 await library.getByRole('button',{name:/Remove saved title/}).click()
 await expect(library.locator('.osa-library-item')).toHaveCount(0)
 await expect(second.locator('.osa-library-item')).toHaveCount(0)
 expect(errors).toEqual([])
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
 await page.screenshot({path:info.outputPath('osa-cinema-v58-library-desktop.png'),fullPage:true,animations:'disabled'})
})

test('V58 responsive private library: mobile, bilingual CTA, local data policy',async ({page},info)=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/osa-cinema/studio/library?lang=ru')
 const library=page.locator('main.osa-library-page')
 await expect(library).toBeVisible()
 await expect(library.getByRole('heading',{name:/ВАША/})).toBeVisible()
 await expect(library.getByRole('heading',{name:'Коллекция пока пуста.'})).toBeVisible()
 await library.getByRole('button',{name:'Switch to English'}).click()
 await expect(library).toHaveAttribute('lang','en')
 await expect(page).toHaveURL(/lang=en/)
 await library.getByRole('link',{name:'Explore the catalogue'}).click()
 await page.getByRole('button',{name:'Add to favorites'}).first().click()
 await page.getByRole('link',{name:'My library'}).first().click()
 await expect(library.locator('.osa-library-item')).toHaveCount(1)
 await expect(library.locator('.osa-library-category')).toContainText('INTERACTIVE')
 await expect(library).toHaveCSS('background-color','rgb(8, 9, 11)')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
 await page.screenshot({path:info.outputPath('osa-cinema-v58-library-mobile.png'),fullPage:true,animations:'disabled'})
})

test('V58 public catalogue JSON serves original factual metadata without video links',async ({request})=>{
 const response=await request.get('/osa-cinema/studio/catalog.v1.json')
 expect(response.status()).toBe(200)
 expect(response.headers()['content-type']).toContain('application/json')
 const json=await response.json()
 expect(json.schema).toBe('OSA_CINEMA_PUBLIC_CATALOG_V1')
 expect(json.total).toBe(3)
 expect(json.languages).toEqual(['ru','en'])
 expect(json.publicPremiereClaimed).toBe(false)
 expect(json.projects.every(p=>p.publicVideoAvailable===false&&p.publicVideoUrl===null)).toBe(true)
 expect(json.projects.filter(p=>p.interactiveUrl!==null)).toHaveLength(1)
})
